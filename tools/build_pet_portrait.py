def _validate_one_predecessor_identity_lineage(
    *,
    reference_path: Path,
    repo_root: Path,
    pet_root: Path,
    form_id: str,
    identity_reference: Path,
) -> dict[str, Any] | None:
    try:
        reference_path.relative_to((repo_root / ".run").resolve())
    except ValueError:
        return None
    candidates: list[tuple[Path, dict[str, list[str]]]] = []
    for result_path in sorted(reference_path.parent.glob("result*.txt")):
        if result_path.is_symlink() or not result_path.is_file():
            continue
        try:
            fields = _parse_generation_result_fields(
                result_path.read_bytes()
            )
            declared_output = _generation_result_output_path(
                fields=fields,
                repo_root=repo_root,
            )
        except PortraitBuildError:
            continue
        if declared_output == reference_path:
            candidates.append((result_path.resolve(), fields))
    if len(candidates) != 1:
        return None
    result_path, fields = candidates[0]
    declared_form_id = _one_generation_result_value(
        fields,
        ("formid", "petid"),
        "predecessor formId",
        required=False,
    )
    if declared_form_id is not None:
        if declared_form_id != form_id:
            return None
    elif result_path.parent.name != form_id:
        return None

    generator_source_text = _one_generation_result_value(
        fields,
        (
            "selectedgeneratorresultpath",
            "selectedgeneratedsource",
            "generatorresultpath",
            "generatorsource",
            "generatedsource",
            "acceptedgeneratedsource",
            "rawsource",
            "resultpath",
            "selectedresultpath",
        ),
        "predecessor generator source",
    )
    assert generator_source_text is not None
    generator_source = _resolve_imagegen_cache_source(
        generator_source_text,
        repo_root=repo_root,
    )
    explicit_generation_id = _one_generation_result_value(
        fields,
        (
            "selectedgeneratorresultid",
            "selectedgenerationid",
            "selectedresultid",
            "generatorresultid",
            "generatorcallid",
            "generationresultid",
            "resultid",
        ),
        "predecessor generation id",
        required=False,
    )
    generation_id = explicit_generation_id or generator_source.stem
    if (
        not CALL_GENERATION_ID_PATTERN.fullmatch(generation_id)
        or generator_source.stem != generation_id
    ):
        return None
    reference_hash = sha256_file(reference_path)
    generator_hash = sha256_file(generator_source)
    if (
        reference_path.stat().st_size != generator_source.stat().st_size
        or reference_hash != generator_hash
    ):
        return None
    declared_hash = _one_generation_result_value(
        fields,
        ("sha256", "rawsha256", "selectedoutputsha256"),
        "predecessor output SHA-256",
        required=False,
    )
    if declared_hash is not None and declared_hash.casefold() != reference_hash:
        return None

    transcript = _find_codex_rollout_transcript(
        generator_source.parent.name
    )
    event_offsets, request_offsets = _matching_transcript_offsets(
        transcript,
        generation_id,
    )
    if len(event_offsets) != 1 or len(request_offsets) != 1:
        return None
    event_offset = next(iter(event_offsets))
    request_offset = next(iter(request_offsets))
    event_raw = _read_transcript_line_at(transcript, event_offset)
    event_binding = _validate_imagegen_end_record(
        raw=event_raw,
        generation_id=generation_id,
        generator_source=generator_source,
        generator_bytes=generator_source.read_bytes(),
    )
    request_raw = _read_transcript_line_at(transcript, request_offset)
    request_hash, arguments_text, arguments = (
        _parse_direct_imagegen_request_record(
            request_raw,
            generation_id,
        )
    )
    request_prompt = arguments.get("prompt")
    if (
        not isinstance(request_prompt, str)
        or not _prompt_declares_dedicated_no_crop(request_prompt)
    ):
        return None
    path_values = arguments.get("referenced_image_paths")
    if not isinstance(path_values, list) or not path_values:
        return None
    references, identity_included = _bind_request_referenced_images(
        values=path_values,
        repo_root=repo_root,
        pet_root=pet_root,
        form_id=form_id,
        identity_reference=identity_reference,
    )
    if not identity_included:
        return None
    return {
        "contract": "imagegen_same_form_predecessor_lineage_v1",
        "outputPathLabel": (
            f"repository:{repo_relative(reference_path, repo_root)}"
        ),
        "outputSha256": reference_hash,
        "resultEvidencePath": repo_relative(result_path, repo_root),
        "resultEvidenceSha256": sha256_file(result_path),
        "generationId": generation_id,
        "generatorSource": _generated_source_label(generator_source),
        "generatorSourceSha256": generator_hash,
        "transcriptPath": _codex_relative(transcript),
        "requestByteOffset": request_offset,
        "requestRecordSha256": request_hash,
        "requestArgumentsUtf8Sha256": sha256_bytes(
            arguments_text.encode("utf-8")
        ),
        "requestPromptUtf8Sha256": sha256_bytes(
            request_prompt.encode("utf-8")
        ),
        "requestPromptHeuristicPassed": True,
        "requestReferencedImages": references,
        "declaredIdentityReferenceIncluded": True,
        "eventByteOffset": event_offset,
        **event_binding,
        "historicalReferencedImageBytesVerified": False,
        "claimLimit": (
            "binds one same-form predecessor output to its canonical cache, "
            "completion event, direct request, and currently readable "
            "declared identity reference; reference path bytes are not "
            "proven unchanged since request time and owner approval remains "
            "required"
        ),
    }


def _validate_predecessor_identity_lineage(
    *,
    reference_values: list[Any],
    repo_root: Path,
    pet_root: Path,
    form_id: str,
    identity_reference: Path,
) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for value in reference_values:
        if not isinstance(value, str):
            continue
        try:
            resolved = Path(value).expanduser().resolve(strict=True)
        except OSError:
            continue
        record = _validate_one_predecessor_identity_lineage(
            reference_path=resolved,
            repo_root=repo_root,
            pet_root=pet_root,
            form_id=form_id,
            identity_reference=identity_reference,
        )
        if record is not None:
            records.append(record)
    return records


def _parse_direct_imagegen_request_record(
    raw: bytes,
    generation_id: str,
) -> tuple[str, str, dict[str, Any]]:
    record = _decode_json_record(raw, "ImageGen request transcript")
    payload = record.get("payload")
    if (
        record.get("type") != "response_item"
        or not isinstance(payload, dict)
        or payload.get("type") != "function_call"
        or payload.get("namespace") != "image_gen"
        or payload.get("name") != "imagegen"
        or payload.get("call_id") != generation_id
    ):
        raise PortraitBuildError(
            "Codex transcript request 未精确绑定 image_gen.imagegen"
        )
    arguments_text = payload.get("arguments")
    arguments = _strict_json_object_text(
        arguments_text,
        "ImageGen request arguments",
    )
    allowed_keys = {
        "prompt",
        "referenced_image_paths",
        "num_last_images_to_include",
    }
    if set(arguments) - allowed_keys:
        raise PortraitBuildError(
            "ImageGen request arguments 包含未知字段："
            f"{sorted(set(arguments) - allowed_keys)}"
        )
    return sha256_bytes(raw), arguments_text, arguments


def _request_compatibility_mode(
    *,
    form_id: str,
    selected_entry: dict[str, Any],
    required_mode: str | None,
) -> str | None:
    declared = selected_entry.get("requestArgumentCompatibility")
    if required_mode is None:
        if declared is not None:
            raise PortraitBuildError(
                "已有可验证 direct request/identity lineage，"
                "不得声明 requestArgumentCompatibility"
            )
        return None
    allowlisted = REQUEST_ARGUMENT_COMPATIBILITY_BY_FORM.get(form_id)
    if allowlisted != required_mode or declared != required_mode:
        raise PortraitBuildError(
            "不可验证的 ImageGen request 仅允许精确 form allowlist "
            "与 selected-sources 显式历史兼容声明："
            f"formId={form_id}, required={required_mode}"
        )
    return required_mode


def _validate_direct_imagegen_request_record(
    raw: bytes,
    generation_id: str,
    *,
    repo_root: Path,
    pet_root: Path,
    form_id: str,
    identity_reference: Path,
    prompt_path: Path,
    selected_entry: dict[str, Any],
) -> tuple[str, dict[str, Any]]:
    request_record_hash, arguments_text, arguments = (
        _parse_direct_imagegen_request_record(raw, generation_id)
    )
    request_prompt = arguments.get("prompt")
    if not isinstance(request_prompt, str):
        raise PortraitBuildError(
            "ImageGen request arguments.prompt 必须是字符串"
        )
    prompt_binding = _request_prompt_binding(
        request_prompt=request_prompt,
        repo_root=repo_root,
        prompt_path=prompt_path,
        selected_entry=selected_entry,
    )

    has_paths = "referenced_image_paths" in arguments
    has_history = "num_last_images_to_include" in arguments
    if has_paths == has_history:
        raise PortraitBuildError(
            "ImageGen portrait request 必须且只能使用 "
            "referenced_image_paths 或 num_last_images_to_include 之一"
        )
    referenced_images: list[dict[str, Any]]
    declared_identity_included: bool | None
    history_count: int | None
    identity_lineage: dict[str, Any]
    compatibility_mode: str | None
    if has_paths:
        path_values = arguments["referenced_image_paths"]
        if not isinstance(path_values, list) or not path_values:
            raise PortraitBuildError(
                "ImageGen request referenced_image_paths "
                "必须是非空数组"
            )
        referenced_images, declared_identity_included = (
            _bind_request_referenced_images(
                values=path_values,
                repo_root=repo_root,
                pet_root=pet_root,
                form_id=form_id,
                identity_reference=identity_reference,
            )
        )
        history_count = None
        reference_mode = "explicit_paths"
        current_reference_content_bound = True
        if declared_identity_included:
            compatibility_mode = _request_compatibility_mode(
                form_id=form_id,
                selected_entry=selected_entry,
                required_mode=None,
            )
            relocations = [
                record["formalIdentityRelocation"]
                for record in referenced_images
                if isinstance(
                    record.get("formalIdentityRelocation"),
                    dict,
                )
            ]
            identity_lineage = {
                "contract": "imagegen_request_identity_lineage_v1",
                "verified": True,
                "mode": (
                    "relocated_direct_declared_identity_reference"
                    if relocations
                    else "direct_declared_identity_reference"
                ),
                "predecessors": [],
            }
            if relocations:
                identity_lineage["formalRelocations"] = relocations
        else:
            predecessors = _validate_predecessor_identity_lineage(
                reference_values=path_values,
                repo_root=repo_root,
                pet_root=pet_root,
                form_id=form_id,
                identity_reference=identity_reference,
            )
            if not predecessors:
                raise PortraitBuildError(
                    "ImageGen request 未直接引用 declared identity，"
                    "且没有同 form、逐字节绑定的 predecessor lineage"
                )
            compatibility_mode = _request_compatibility_mode(
                form_id=form_id,
                selected_entry=selected_entry,
                required_mode=None,
            )
            identity_lineage = {
                "contract": "imagegen_request_identity_lineage_v1",
                "verified": True,
                "mode": "same_form_predecessor_generation",
                "predecessors": predecessors,
            }
    else:
        history_value = arguments["num_last_images_to_include"]
        if (
            not isinstance(history_value, int)
            or isinstance(history_value, bool)
            or not 1 <= history_value <= 5
        ):
            raise PortraitBuildError(
                "ImageGen request num_last_images_to_include "
                "必须是 1..5 的整数"
            )
        referenced_images = []
        declared_identity_included = None
        history_count = history_value
        reference_mode = "conversation_history"
        current_reference_content_bound = False
        compatibility_mode = _request_compatibility_mode(
            form_id=form_id,
            selected_entry=selected_entry,
            required_mode=(
                "historical_conversation_image_request_owner_pending_v1"
            ),
        )
        identity_lineage = {
            "contract": "imagegen_request_identity_lineage_v1",
            "verified": False,
            "mode": "unrecoverable_conversation_history_compatibility",
            "predecessors": [],
        }

    arguments_bytes = arguments_text.encode("utf-8")
    canonical_arguments = json.dumps(
        arguments,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    binding = {
        "contract": "imagegen_request_arguments_binding_v1",
        "requestArgumentBindingVerified": True,
        "unverifiedReason": None,
        "argumentsUtf8Sha256": sha256_bytes(arguments_bytes),
        "argumentsUtf8ByteLength": len(arguments_bytes),
        "argumentsCanonicalJsonSha256": sha256_bytes(
            canonical_arguments
        ),
        "argumentKeys": sorted(arguments),
        "prompt": prompt_binding,
        "documentedPrompt": None,
        "referenceMode": reference_mode,
        "numLastImagesToInclude": history_count,
        "referencedImages": referenced_images,
        "identityLineage": identity_lineage,
        "compatibilityMode": compatibility_mode,
        "automaticApprovalEligible": False,
        "currentReferencedImageContentBound": (
            current_reference_content_bound
        ),
        "historicalReferencedImageBytesVerified": False,
        "declaredIdentityReferenceIncluded": (
            declared_identity_included
        ),
        "claimLimit": (
            "binds the recorded direct ImageGen JSON arguments and the "
            "currently readable bytes of explicit reference paths; path "
            "records do not prove those bytes were unchanged since request "
            "time, conversation-history image content is not recoverable, "
            "and this does not prove semantic independence, copyright "
            "provenance, or owner approval"
        ),
    }
    return request_record_hash, binding


