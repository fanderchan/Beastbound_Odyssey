def _decode_json_object_snapshot(
    payload: bytes,
    path: Path,
    label: str,
) -> dict[str, Any]:
    try:
        value = json.loads(payload.decode("utf-8"))
    except (UnicodeError, json.JSONDecodeError) as exc:
        raise PortraitBuildError(
            f"{label} snapshot 不是合法 JSON：{path}: {exc}"
        ) from exc
    if not isinstance(value, dict):
        raise PortraitBuildError(
            f"{label} snapshot 顶层必须是对象：{path}"
        )
    return value


def _assert_file_snapshots_unchanged(
    snapshots: tuple[tuple[Path, bytes, str], ...],
) -> None:
    """Fail closed if any authority path changed after its entry snapshot."""

    for path, expected, label in snapshots:
        current = _read_regular_file_snapshot(path, label)
        if (
            len(current) != len(expected)
            or sha256_bytes(current) != sha256_bytes(expected)
        ):
            raise PortraitBuildError(
                f"{label}在入口 snapshot 后发生漂移：{path}"
            )


def _read_json_object(path: Path, label: str) -> dict[str, Any]:
    if not path.is_file():
        raise PortraitBuildError(f"缺少{label}：{path}")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise PortraitBuildError(f"{label}不是合法 JSON：{path}: {exc}") from exc
    if not isinstance(value, dict):
        raise PortraitBuildError(f"{label}顶层必须是对象：{path}")
    return value


def _normalize_evidence_key(value: str) -> str:
    return re.sub(r"[^a-z0-9]", "", value.casefold())


def _strip_evidence_value(value: str) -> str:
    stripped = value.strip()
    if "\x00" in stripped:
        raise PortraitBuildError("ImageGen result evidence 包含 NUL")
    if (
        len(stripped) >= 2
        and stripped[0] == stripped[-1]
        and stripped[0] in {"'", '"'}
    ):
        stripped = stripped[1:-1].strip()
    return stripped


def _parse_generation_result_fields(
    result_bytes: bytes,
) -> dict[str, list[str]]:
    if len(result_bytes) > 512 * 1024:
        raise PortraitBuildError("ImageGen result evidence 超过 512 KiB")
    try:
        text = result_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PortraitBuildError(
            f"ImageGen result evidence 必须是 UTF-8 文本：{exc}"
        ) from exc
    if not text.strip():
        raise PortraitBuildError("ImageGen result evidence 不能为空")
    fields: dict[str, list[str]] = {}
    line_pattern = re.compile(
        r"^([A-Za-z][A-Za-z0-9_. -]{0,63})\s*[:=]\s*(.*)$"
    )
    for line in text.splitlines():
        match = line_pattern.match(line)
        if match is None:
            continue
        key = _normalize_evidence_key(match.group(1))
        value = _strip_evidence_value(match.group(2))
        if value:
            fields.setdefault(key, []).append(value)
    return fields


def _one_generation_result_value(
    fields: dict[str, list[str]],
    keys: tuple[str, ...],
    label: str,
    *,
    required: bool = True,
) -> str | None:
    values: list[str] = []
    for key in keys:
        values.extend(fields.get(key, ()))
    if not values:
        if required:
            raise PortraitBuildError(
                f"ImageGen result evidence 缺少唯一 {label}"
            )
        return None
    if len(values) != 1:
        raise PortraitBuildError(
            f"ImageGen result evidence 的 {label} 不唯一：{values}"
        )
    return values[0]


def _canonical_json_sha256(value: Any) -> str:
    return sha256_bytes(
        json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    )


