#!/usr/bin/env python3
"""Build one canonical, independently authored Beastbound pet headshot.

The creative input is a dedicated head-and-upper-body composition generated by
the built-in image generator against one solid chroma background.  This tool
does not crop an identity/world/battle frame into a portrait.  It only:

* archives the untouched decoded source as lossless WebP;
* creates alpha and exact same-operation chroma eligibility masks;
* applies the allowlisted mask-bounded edge cleanup without changing alpha;
* fits the complete composition onto a transparent 1024px master;
* derives the shared 512px runtime portrait through the existing canonical
  premultiplied resize helper; and
* writes prompt, ownership, immutable hashes, metadata, and compact-size QA.

Use ``--create-generation-attestation .run/.../generation-attestation.json``
with an independently existing ``--generation-result .run/.../result.txt``
first to create the strict input/prompt/identity/generation binding.  The
result record must resolve to the selected built-in ImageGen cache output and
the exact workspace PNG bytes; this writer cannot create that evidence.  The
default build mode is a validating dry run.  ``--write`` installs the complete
file set with rollback and atomic no-clobber links.  Existing or late-created
files are never replaced; visual replacement must use a separate staged root
and the repository's controlled publication workflow.
"""

