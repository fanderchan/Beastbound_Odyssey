def _read_image(path: Path, label: str) -> tuple[Image.Image, str, str]:
    if not path.is_file():
        raise PortraitBuildError(f"缺少{label}：{path}")
    try:
        with Image.open(path) as opened:
            opened.load()
            image_format = opened.format or ""
            mode = opened.mode
            return opened.copy(), image_format, mode
    except (OSError, UnidentifiedImageError) as exc:
        raise PortraitBuildError(f"{label}不可解码：{path}: {exc}") from exc


def _read_regular_file_snapshot(path: Path, label: str) -> bytes:
    """Read one canonical regular file without following a final symlink."""

    file_fd: int | None = None
    try:
        file_fd = os.open(
            path,
            os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0),
        )
        file_stat = os.fstat(file_fd)
        if not stat.S_ISREG(file_stat.st_mode):
            raise PortraitBuildError(
                f"{label}不是普通文件：{path}"
            )
        chunks: list[bytes] = []
        while True:
            chunk = os.read(file_fd, 1024 * 1024)
            if not chunk:
                break
            chunks.append(chunk)
        return b"".join(chunks)
    except OSError as exc:
        raise PortraitBuildError(
            f"无法读取{label} snapshot：{path}: {exc}"
        ) from exc
    finally:
        if file_fd is not None:
            os.close(file_fd)


