def _closed_registration_file_index(
    value: Any,
    *,
    label: str,
) -> dict[str, dict[str, Any]]:
    """Parse one exact, traversal-free closed-registration file list."""

    if not isinstance(value, list):
        raise PortraitBuildError(f"{label}必须是数组")
    records: dict[str, dict[str, Any]] = {}
    ordered_paths: list[str] = []
    for index, item in enumerate(value):
        if not isinstance(item, dict) or set(item) != {
            "path",
            "sha256",
            "size",
        }:
            raise PortraitBuildError(
                f"{label}[{index}] 必须严格包含 path/sha256/size"
            )
        path_value = item.get("path")
        digest = item.get("sha256")
        size = item.get("size")
        if (
            not isinstance(path_value, str)
            or not path_value
            or path_value.startswith("/")
            or "\\" in path_value
        ):
            raise PortraitBuildError(
                f"{label}[{index}].path 必须是非空 POSIX 相对路径"
            )
        parts = path_value.split("/")
        if (
            any(part in {"", ".", ".."} for part in parts)
            or Path(path_value).as_posix() != path_value
        ):
            raise PortraitBuildError(
                f"{label}[{index}].path 包含非规范或越界片段"
            )
        if not isinstance(digest, str) or not SHA256_PATTERN.fullmatch(digest):
            raise PortraitBuildError(
                f"{label}[{index}].sha256 必须是小写 SHA-256"
            )
        if (
            not isinstance(size, int)
            or isinstance(size, bool)
            or size <= 0
        ):
            raise PortraitBuildError(
                f"{label}[{index}].size 必须是正整数"
            )
        if path_value in records:
            raise PortraitBuildError(f"{label}包含重复 path：{path_value}")
        records[path_value] = item
        ordered_paths.append(path_value)
    if ordered_paths != sorted(ordered_paths):
        raise PortraitBuildError(f"{label}必须按 path 严格升序")
    return records


