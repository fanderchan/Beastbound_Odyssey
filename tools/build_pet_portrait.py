def _write_identity_freeze_ledger_pinned(
    options: IdentityFreezeLedgerOptions,
    *,
    pinned_repo_root: Path,
    repo_root_fd: int,
    pinned_pet_root: Path,
    pet_root_fd: int,
    output_parent_fd: int,
) -> dict[str, Any]:
    """Freeze one explicitly allowlisted legacy identity for portrait import.

    The ledger is deliberately honest: it binds the current tracked identity
    snapshot and its catalog authorities, but never claims that the historical
    identity extraction pipeline can be replayed.
    """

    repo_root = pinned_repo_root
    pet_root = _resolve_inside(
        options.repo_root,
        options.pet_root,
        "宠物资源根目录",
    )
    if pet_root != pinned_pet_root:
        raise PortraitBuildError(
            "宠物资源根目录与入口 pinned pet root 不一致"
        )
    catalog_path = _resolve_inside(
        options.repo_root,
        options.catalog_path,
        "pet_art_catalog",
    )
    identity_reference = _resolve_inside(
        options.repo_root,
        options.identity_reference,
        "身份参考",
    )
    if options.form_id not in LEGACY_IDENTITY_FREEZE_ALLOWLIST:
        raise PortraitBuildError(
            "portrait identity compatibility ledger 仅允许已审计的 "
            "5 个 legacy form"
        )
    if identity_reference != (
        pet_root / "identity/front_3quarter_sw.png"
    ).resolve():
        raise PortraitBuildError(
            "compatibility ledger 只允许 identity/front_3quarter_sw.png"
        )
    catalog_record = _formal_catalog_form(
        repo_root=repo_root,
        catalog_path=catalog_path,
        form_id=options.form_id,
    )
    pet = catalog_record.get("pet")
    if not isinstance(pet, dict):
        raise PortraitBuildError("catalog pet identity evidence 缺失")
    catalog_root = _resolve_inside(
        repo_root,
        Path(str(pet.get("root", ""))),
        "catalog pet root",
    )
    if catalog_root != pet_root:
        raise PortraitBuildError(
            "compatibility ledger pet root 与 catalog 不一致"
        )
    resolved: dict[str, Path] = {}
    for field in (
        "metadataPath",
        "identityPath",
        "ownershipPath",
        "promptPath",
    ):
        value = pet.get(field)
        if not isinstance(value, str) or not value:
            raise PortraitBuildError(
                f"catalog pet.{field} 缺失"
            )
        path = _resolve_inside(
            repo_root,
            Path(value),
            f"catalog pet.{field}",
        )
        try:
            path.relative_to(pet_root)
        except ValueError as exc:
            raise PortraitBuildError(
                f"catalog pet.{field} 不在当前 pet root"
            ) from exc
        if not path.is_file():
            raise PortraitBuildError(
                f"catalog pet.{field} 不存在：{path}"
            )
        resolved[field] = path

    action_meta = _read_json_object(
        resolved["metadataPath"],
        "pet identity bundle metadata",
    )
    if action_meta.get("formId") != options.form_id:
        raise PortraitBuildError(
            "pet identity bundle metadata.formId 漂移"
        )
    identity_contract = action_meta.get("identity")
    if isinstance(identity_contract, dict):
        poses = identity_contract.get("poses")
        if (
            not isinstance(poses, dict)
            or poses.get("front_3quarter_sw")
            != "identity/front_3quarter_sw.png"
        ):
            raise PortraitBuildError(
                "metadata 未精确声明 front_3quarter_sw identity pose"
            )
        binding_mode = "metadata_pose"
    elif (
        action_meta.get("identityLock")
        == repo_relative(resolved["identityPath"], pet_root)
        and isinstance(action_meta.get("views"), list)
        and "front_3quarter_sw" in action_meta["views"]
    ):
        binding_mode = "legacy_metadata_view_pose"
    else:
        raise PortraitBuildError(
            "legacy metadata identity contract 不完整"
        )

    source_archive = action_meta.get("sourceArchive")
    pipeline_value = (
        source_archive.get("pipelineMetadata")
        if isinstance(source_archive, dict)
        else None
    )
    if isinstance(pipeline_value, str):
        pipeline_path = _resolve_pet_relative_path(
            pet_root,
            pipeline_value,
            "identity pipeline metadata",
        )
    else:
        candidates = [
            path.resolve()
            for path in (
                pet_root / "source/identity-board-pipeline-meta.json",
                pet_root / "identity/identity-board-pipeline-meta.json",
            )
            if path.is_file()
        ]
        if len(candidates) != 1:
            raise PortraitBuildError(
                "identity pipeline metadata 必须恰好存在一份"
            )
        pipeline_path = candidates[0]
    _read_json_object(pipeline_path, "identity pipeline metadata")

    ledger = _expected_identity_freeze_ledger(
        repo_root=repo_root,
        pet_root=pet_root,
        form_id=options.form_id,
        identity_reference=identity_reference,
        reference_role="front_3quarter_sw",
        binding_mode=binding_mode,
        metadata_path=resolved["metadataPath"],
        identity_lock_path=resolved["identityPath"],
        ownership_path=resolved["ownershipPath"],
        prompt_path=resolved["promptPath"],
        pipeline_path=pipeline_path,
        catalog_path=catalog_path,
        catalog_record=catalog_record,
    )
    output_path = pet_root / IDENTITY_FREEZE_LEDGER_PATH
    if output_path.exists() or output_path.is_symlink():
        raise PortraitBuildError(
            "portrait identity compatibility ledger 已存在，永久拒绝覆盖："
            f"{output_path}"
        )
    payload = (
        json.dumps(ledger, ensure_ascii=False, indent=2) + "\n"
    ).encode("utf-8")
    _publish_with_pinned_parent_no_clobber(
        root_fd=pet_root_fd,
        pinned_parent_fd=output_parent_fd,
        parent_relative=IDENTITY_FREEZE_LEDGER_PATH.parent,
        filename=IDENTITY_FREEZE_LEDGER_PATH.name,
        payload=payload,
        display_root=pet_root,
        label="portrait identity compatibility ledger",
        absolute_bindings=(
            (
                repo_root,
                repo_root_fd,
                "identity ledger repo root",
            ),
            (
                pet_root,
                pet_root_fd,
                "identity ledger pet root",
            ),
        ),
    )
    return ledger


def write_identity_freeze_ledger(
    options: IdentityFreezeLedgerOptions,
) -> dict[str, Any]:
    """Pin repository and pet roots before validating legacy evidence."""

    supplied_repo_root = options.repo_root.absolute()
    repo_root = options.repo_root.resolve()
    if not repo_root.is_dir():
        raise PortraitBuildError(f"仓库目录不存在：{repo_root}")
    repo_root_fd = _open_absolute_directory(repo_root)
    try:
        pet_root = _resolve_inside(
            supplied_repo_root,
            options.pet_root,
            "宠物资源根目录",
        )
        pet_relative = pet_root.relative_to(repo_root)
        pet_root_fd = _open_directory_chain_from_fd(
            repo_root_fd,
            pet_relative,
            create=False,
            display_root=repo_root,
        )
        try:
            output_parent_fd = _open_directory_chain_from_fd(
                pet_root_fd,
                IDENTITY_FREEZE_LEDGER_PATH.parent,
                create=True,
                display_root=pet_root,
            )
            try:
                return _write_identity_freeze_ledger_pinned(
                    options,
                    pinned_repo_root=repo_root,
                    repo_root_fd=repo_root_fd,
                    pinned_pet_root=pet_root,
                    pet_root_fd=pet_root_fd,
                    output_parent_fd=output_parent_fd,
                )
            finally:
                os.close(output_parent_fd)
        finally:
            os.close(pet_root_fd)
    finally:
        os.close(repo_root_fd)


def _validate_identity_evidence(
    *,
    repo_root: Path,
    pet_root: Path,
    form_id: str,
    identity_reference: Path,
    catalog_path: Path,
    isolated: bool,
) -> dict[str, Any]:
    catalog_record: dict[str, Any] | None = None
    catalog_binding: dict[str, Any] | None = None
    if isolated:
        metadata_path = pet_root / "action-bundle-meta.json"
        identity_lock_path = pet_root / "identity/identity-lock.md"
    else:
        catalog_record = _formal_catalog_form(
            repo_root=repo_root,
            catalog_path=catalog_path,
            form_id=form_id,
        )
        pet = catalog_record.get("pet")
        if not isinstance(pet, dict):
            raise PortraitBuildError(
                f"{form_id}.pet catalog evidence 缺失"
            )
        required_catalog_fields = (
            "root",
            "metadataPath",
            "identityPath",
            "ownershipPath",
            "promptPath",
        )
        missing = [
            field
            for field in required_catalog_fields
            if not isinstance(pet.get(field), str) or not pet[field]
        ]
        if missing:
            raise PortraitBuildError(
                f"{form_id}.pet catalog identity evidence 缺字段：{missing}"
            )
        catalog_root = _resolve_inside(
            repo_root,
            Path(pet["root"]),
            f"{form_id}.pet.root",
        )
        if catalog_root != pet_root:
            raise PortraitBuildError(
                f"{form_id}.pet.root 未绑定当前 pet root"
            )
        metadata_path = _resolve_inside(
            repo_root,
            Path(pet["metadataPath"]),
            f"{form_id}.pet.metadataPath",
        )
        identity_lock_path = _resolve_inside(
            repo_root,
            Path(pet["identityPath"]),
            f"{form_id}.pet.identityPath",
        )
        ownership_path = _resolve_inside(
            repo_root,
            Path(pet["ownershipPath"]),
            f"{form_id}.pet.ownershipPath",
        )
        prompt_path = _resolve_inside(
            repo_root,
            Path(pet["promptPath"]),
            f"{form_id}.pet.promptPath",
        )
        for path, label in (
            (metadata_path, "metadataPath"),
            (identity_lock_path, "identityPath"),
            (ownership_path, "ownershipPath"),
            (prompt_path, "promptPath"),
        ):
            try:
                path.relative_to(pet_root)
            except ValueError as exc:
                raise PortraitBuildError(
                    f"{form_id}.pet.{label} 必须位于 catalog pet.root 内"
                ) from exc
            if not path.is_file():
                raise PortraitBuildError(
                    f"{form_id}.pet.{label} 不存在：{path}"
                )
        catalog_binding = {
            "path": repo_relative(catalog_path, repo_root),
            "formIdentitySliceSha256": _canonical_json_sha256(
                catalog_record
            ),
            "ownershipPath": repo_relative(ownership_path, repo_root),
            "ownershipSha256": sha256_file(ownership_path),
            "promptPath": repo_relative(prompt_path, repo_root),
            "promptSha256": sha256_file(prompt_path),
        }

    if not metadata_path.is_file():
        raise PortraitBuildError(
            f"缺少 pet identity bundle metadata：{metadata_path}"
        )
    if not identity_lock_path.is_file():
        raise PortraitBuildError(
            f"缺少 pet identity lock：{identity_lock_path}"
        )
    action_meta = _read_json_object(
        metadata_path,
        "pet identity bundle metadata",
    )
    if action_meta.get("formId") != form_id:
        raise PortraitBuildError(
            "pet identity bundle metadata.formId 与当前 form-id 不一致"
        )
    if not isinstance(action_meta.get("schemaVersion"), int):
        raise PortraitBuildError(
            "pet identity bundle metadata.schemaVersion 缺失"
        )

    identity_contract = action_meta.get("identity")
    if identity_contract is None:
        identity_contract = action_meta.get("identityLock")
    reference_role: str | None = None
    binding_mode: str
    identity_status: str
    declared_lock: str | None = None
    if isinstance(identity_contract, dict):
        poses = identity_contract.get("poses")
        if not isinstance(poses, dict) or not poses:
            raise PortraitBuildError(
                "pet identity bundle metadata.identity.poses 缺失"
            )
        for role, value in poses.items():
            if not isinstance(role, str) or not isinstance(value, str):
                raise PortraitBuildError(
                    "pet identity bundle metadata.identity.poses 非法"
                )
            pose_path = _resolve_pet_relative_path(
                pet_root,
                value,
                f"identity pose {role}",
            )
            if pose_path == identity_reference:
                reference_role = role
        if reference_role is None:
            raise PortraitBuildError(
                "identity reference 必须精确等于 bundle metadata "
                "声明的 canonical identity pose"
            )
        declared_lock_value = identity_contract.get("identityLock")
        if declared_lock_value is not None:
            if not isinstance(declared_lock_value, str):
                raise PortraitBuildError(
                    "identity.identityLock 必须是字符串"
                )
            declared_lock = declared_lock_value
        identity_status_value = identity_contract.get("status")
        if not isinstance(identity_status_value, str):
            raise PortraitBuildError(
                "identity.status 缺失，不能证明身份已冻结"
            )
        identity_status = identity_status_value
        binding_mode = "metadata_pose"
    elif isinstance(identity_contract, str):
        declared_lock = identity_contract
        views = action_meta.get("views")
        if not isinstance(views, list) or not all(
            isinstance(view, str) for view in views
        ):
            raise PortraitBuildError(
                "legacy identity bundle 缺少 canonical views"
            )
        for view in views:
            legacy_pose = pet_root / f"identity/{view}.png"
            if legacy_pose.resolve() == identity_reference:
                reference_role = view
        if reference_role is None:
            raise PortraitBuildError(
                "legacy identity reference 必须精确等于 "
                "identity/<canonical view>.png"
            )
        art_status = action_meta.get("artStatus")
        owner_status = action_meta.get("ownerReviewStatus")
        if art_status not in {
            "in_production",
            "owner_review_pending",
            "approved",
        } or owner_status not in {"pending", "approved"}:
            raise PortraitBuildError(
                "legacy identity bundle 状态不足以证明身份已冻结"
            )
        identity_status = (
            "approved"
            if owner_status == "approved"
            else "legacy_identity_lock_owner_pending"
        )
        binding_mode = "legacy_metadata_view_pose"
    else:
        raise PortraitBuildError(
            "pet identity bundle metadata 缺少 identity 合同"
        )
    if reference_role != "front_3quarter_sw":
        raise PortraitBuildError(
            "portrait identity reference 必须精确绑定 "
            "front_3quarter_sw canonical pose"
        )
    expected_front_path = (
        pet_root / "identity/front_3quarter_sw.png"
    ).resolve()
    if identity_reference != expected_front_path:
        raise PortraitBuildError(
            "portrait identity reference 必须精确等于 "
            "identity/front_3quarter_sw.png"
        )

    if identity_status not in {
        "self_review_passed_owner_pending",
        "self_review_passed_owner_review_pending",
        "legacy_identity_lock_owner_pending",
        "approved",
    }:
        raise PortraitBuildError(
            f"identity status 尚未冻结：{identity_status}"
        )
    if declared_lock is not None:
        resolved_declared_lock = _resolve_pet_relative_path(
            pet_root,
            declared_lock,
            "identity lock",
        )
        if resolved_declared_lock != identity_lock_path:
            raise PortraitBuildError(
                "bundle metadata 的 identity lock 与 catalog/default "
                "identity lock 不一致"
            )
    if identity_lock_path.stat().st_size < 64:
        raise PortraitBuildError("identity lock 过短，不能作为冻结证据")

    source_archive = action_meta.get("sourceArchive")
    pipeline_value = (
        source_archive.get("pipelineMetadata")
        if isinstance(source_archive, dict)
        else None
    )
    if pipeline_value is not None:
        if not isinstance(pipeline_value, str):
            raise PortraitBuildError(
                "sourceArchive.pipelineMetadata 必须是字符串"
            )
        pipeline_path = _resolve_pet_relative_path(
            pet_root,
            pipeline_value,
            "identity pipeline metadata",
        )
    else:
        candidates = [
            path
            for path in (
                pet_root / "source/identity-board-pipeline-meta.json",
                pet_root / "identity/identity-board-pipeline-meta.json",
            )
            if path.is_file()
        ]
        if len(candidates) != 1:
            raise PortraitBuildError(
                "identity pipeline metadata 必须恰好存在一份"
            )
        pipeline_path = candidates[0].resolve()
    pipeline_meta = _read_json_object(
        pipeline_path,
        "identity pipeline metadata",
    )
    frames = pipeline_meta.get("frames")
    if not isinstance(frames, list) or len(frames) < 2:
        raise PortraitBuildError(
            "identity pipeline metadata.frames 不完整"
        )
    slots = pipeline_meta.get("slots")
    if slots is not None and (
        not isinstance(slots, list) or reference_role not in slots
    ):
        raise PortraitBuildError(
            "identity pipeline metadata 未声明 reference role"
        )
    if slots is None:
        frame_labels = pipeline_meta.get("frame_labels")
        if not isinstance(frame_labels, list) or len(frame_labels) != len(
            frames
        ):
            raise PortraitBuildError(
                "legacy identity pipeline metadata 缺少完整 frame_labels"
            )
    reference_image, reference_format, reference_mode = _read_image(
        identity_reference,
        "身份参考",
    )
    reference_rgba_hash = rgba_hash(reference_image.convert("RGBA"))
    matching_frame = next(
        (
            frame
            for frame in frames
            if isinstance(frame, dict)
            and frame.get("slot") == reference_role
        ),
        None,
    )
    pipeline_pixel_hash_verified = False
    if isinstance(matching_frame, dict) and isinstance(
        matching_frame.get("sourceRgbaSha256"),
        str,
    ):
        if matching_frame["sourceRgbaSha256"] != reference_rgba_hash:
            raise PortraitBuildError(
                "identity reference 像素与 frozen pipeline metadata 不一致"
            )
        pipeline_pixel_hash_verified = True

    identity_gate = action_meta.get("evidence")
    identity_gate = (
        identity_gate.get("identityGateAudit")
        if isinstance(identity_gate, dict)
        else None
    )
    compatibility_ledger: dict[str, Any] | None = None
    if isolated:
        if not isinstance(identity_gate, dict):
            raise PortraitBuildError(
                "isolated fusion pet 缺少 identityGateAudit 冻结证据"
            )
        pipeline_gate = identity_gate.get("pipelineMetadata")
        if not isinstance(pipeline_gate, dict):
            raise PortraitBuildError(
                "isolated fusion identityGateAudit.pipelineMetadata 缺失"
            )
        if pipeline_gate.get("path") != repo_relative(
            pipeline_path,
            pet_root,
        ):
            raise PortraitBuildError(
                "isolated fusion identityGateAudit pipeline path 漂移"
            )
        if pipeline_gate.get("sha256") != sha256_file(pipeline_path):
            raise PortraitBuildError(
                "isolated fusion identityGateAudit pipeline hash 漂移"
            )
        gate_sources = pipeline_gate.get("sources")
        gate_reference = (
            gate_sources.get(reference_role)
            if isinstance(gate_sources, dict)
            else None
        )
        if not isinstance(gate_reference, dict):
            raise PortraitBuildError(
                "isolated fusion identityGateAudit 缺少 reference pose"
            )
        gate_hash = gate_reference.get("canonicalRgbaSha256")
        if not isinstance(gate_hash, str):
            raise PortraitBuildError(
                "isolated fusion identityGateAudit reference hash 缺失"
            )
        if (
            not isinstance(matching_frame, dict)
            or not isinstance(
                matching_frame.get("sourceRgbaSha256"),
                str,
            )
            or matching_frame["sourceRgbaSha256"]
            != reference_rgba_hash
            or gate_hash != reference_rgba_hash
        ):
            raise PortraitBuildError(
                "isolated fusion identityGateAudit、pipeline frame 与"
                "当前 reference RGBA hash 必须三方一致"
            )
        pipeline_pixel_hash_verified = True
        isolated_ownership = (
            pet_root / "identity/source-and-ownership.md"
        )
        isolated_prompt = pet_root / "prompts/identity.txt"
        for path, label in (
            (isolated_ownership, "isolated identity ownership"),
            (isolated_prompt, "isolated identity prompt"),
        ):
            if not path.is_file():
                raise PortraitBuildError(f"{label} 缺失：{path}")
        catalog_binding = {
            "path": None,
            "formIdentitySliceSha256": None,
            "ownershipPath": repo_relative(
                isolated_ownership,
                repo_root,
            ),
            "ownershipSha256": sha256_file(isolated_ownership),
            "promptPath": repo_relative(isolated_prompt, repo_root),
            "promptSha256": sha256_file(isolated_prompt),
        }
    elif not pipeline_pixel_hash_verified:
        if form_id not in LEGACY_IDENTITY_FREEZE_ALLOWLIST:
            raise PortraitBuildError(
                "formal pet 缺少 frozen pipeline reference hash，"
                "且不在显式 legacy compatibility allowlist"
            )
        ledger_path = pet_root / IDENTITY_FREEZE_LEDGER_PATH
        if not ledger_path.is_file():
            raise PortraitBuildError(
                "legacy identity reference 缺少 portrait-specific "
                f"compatibility ledger：{ledger_path}"
            )
        assert catalog_record is not None
        assert catalog_binding is not None
        expected_ledger = _expected_identity_freeze_ledger(
            repo_root=repo_root,
            pet_root=pet_root,
            form_id=form_id,
            identity_reference=identity_reference,
            reference_role=reference_role,
            binding_mode=binding_mode,
            metadata_path=metadata_path,
            identity_lock_path=identity_lock_path,
            ownership_path=ownership_path,
            prompt_path=prompt_path,
            pipeline_path=pipeline_path,
            catalog_path=catalog_path,
            catalog_record=catalog_record,
        )
        actual_ledger = _read_json_object(
            ledger_path,
            "portrait identity compatibility ledger",
        )
        if actual_ledger != expected_ledger:
            raise PortraitBuildError(
                "portrait identity compatibility ledger "
                "与当前 catalog-bound identity evidence 不一致"
            )
        compatibility_ledger = {
            "path": repo_relative(ledger_path, repo_root),
            "sha256": sha256_file(ledger_path),
            "trustLevel": "catalog_bound_legacy_freeze",
            "historicalPipelineReplayVerified": False,
        }
    return {
        "contract": "pet_identity_bundle_binding_v1",
        "bindingMode": binding_mode,
        "formId": form_id,
        "bundleMetadataPath": repo_relative(metadata_path, repo_root),
        "bundleMetadataSha256": sha256_file(metadata_path),
        "identityLockPath": repo_relative(identity_lock_path, repo_root),
        "identityLockSha256": sha256_file(identity_lock_path),
        "identityStatus": identity_status,
        "referenceRole": reference_role,
        "referencePath": repo_relative(identity_reference, repo_root),
        "referenceSha256": sha256_file(identity_reference),
        "referenceRgbaSha256": reference_rgba_hash,
        "referenceWidth": reference_image.width,
        "referenceHeight": reference_image.height,
        "referenceMode": reference_mode,
        "referenceFormat": reference_format,
        "pipelineMetadataPath": repo_relative(pipeline_path, repo_root),
        "pipelineMetadataSha256": sha256_file(pipeline_path),
        "pipelinePixelHashVerified": pipeline_pixel_hash_verified,
        "currentReferencePixelBindingVerified": (
            pipeline_pixel_hash_verified
            or compatibility_ledger is not None
        ),
        "compatibilityLedger": compatibility_ledger,
        "catalogEvidence": catalog_binding,
    }


def _prompt_declares_dedicated_no_crop(prompt_text: str) -> bool:
    lowered = prompt_text.casefold()
    identifies_headshot = any(
        token in lowered
        for token in ("headshot", "portrait", "大头照", "头像", "头肩")
    )
    crop_word = r"crop(?:ped|ping)?"
    direct_or_coordinated = any(
        re.search(pattern, lowered)
        for pattern in (
            rf"\b(?:no|never|without)\s+"
            rf"(?:(?:an?|being)\s+)?{crop_word}\b",
            rf"\bnot\s+(?:an?\s+)?{crop_word}\b",
            rf"\bdo not\s+{crop_word}\b",
            rf"\b(?:must|should|may|can)\s+not\s+"
            rf"(?:be\s+)?{crop_word}\b",
            # A bounded grammatical coordination is safe even when the crop
            # verb is farther than 24 characters from "do not".
            rf"\bdo not\s+[^,.;:!?\n]{{1,48}}\s+"
            rf"(?:or|and)\s+{crop_word}\b",
            rf"\bdo not\s+[^.;:!?\n]{{1,160}}\b{crop_word}\b",
            # Likewise for a comma-separated negative verb list such as
            # "Do not redesign, recolor, add, remove, or crop ...".
            rf"\bdo not\s+"
            rf"(?:[^,.;:!?\n]{{1,32}},\s*){{1,8}}"
            rf"(?:or|and)\s+{crop_word}\b",
            r"(禁止|不得|不可|不要).{0,12}裁",
        )
    )
    constraint_list_forbids_crop = False
    header_pattern = re.compile(
        r"(?:^|[.!?;]\s+)(constraints?|avoid|negative prompt)\s*:\s*(.*)$"
    )
    for line in lowered.splitlines():
        header = header_pattern.search(line)
        if header is None:
            continue
        header_name = header.group(1)
        for clause in re.split(r"[.!?;]", header.group(2)):
            if re.search(rf"\b{crop_word}\b", clause) is None:
                continue
            # "Avoid: ... cropped parts" is intrinsically a negative list.
            # A generic Constraints line is accepted only when the same
            # sentence-level clause begins with "No"; this prevents a distant
            # "No ..." in one sentence from authorizing "Crop ..." in another.
            if header_name == "avoid" or re.match(r"^\s*no\b", clause):
                constraint_list_forbids_crop = True
                break
        if constraint_list_forbids_crop:
            break
    forbids_crop = direct_or_coordinated or constraint_list_forbids_crop
    if not identifies_headshot or not forbids_crop:
        return False

    # A negative sentence is not a license for a later affirmative derivation
    # instruction.  Evaluate sentence/line clauses independently so text such
    # as "Never crop. Crop this portrait from the identity board." fails
    # closed instead of passing because the first sentence contained "never".
    derivation_verbs = (
        r"crop(?:ped|ping)?|deriv(?:e|ed|ing)|"
        r"reus(?:e|ed|ing)|extract(?:ed|ing)?|trac(?:e|ed|ing)|"
        r"zoom(?:ed|ing)?|resiz(?:e|ed|ing)|past(?:e|ed|ing)|"
        r"refram(?:e|ed|ing)|enlarg(?:e|ed|ing|ement)|"
        r"cop(?:y|ied|ying)|cut[- ]?out(?:s)?|"
        r"cut(?:ting)?\s+out|screen[- ]?shot(?:s)?|"
        r"convert(?:ed|ing)?|transform(?:ed|ing)?|"
        r"repurpos(?:e|ed|ing)|tak(?:e|en|ing)"
    )
    protected_sources = (
        r"identity(?:[- ]board|[- ]art|[- ]image)?|full[- ]body|"
        r"world(?:[- ]art|[- ]frame)?|battle(?:[- ]art|[- ]frame)?|"
        r"mounted(?:[- ]art|[- ]frame)?|showcase"
    )
    local_negators = (
        r"(?:\bno\b|\bnot\b|\bnever\b|\bwithout\b|"
        r"\brather\s+than\b|"
        r"\bdo\s+not\b|\bmust\s+not\b|\bshould\s+not\b|"
        r"\bmay\s+not\b|\bcan\s+not\b|\bcannot\b|"
        r"禁止|不得|不可|不要)"
    )
    strong_coordinated_negators = (
        r"(?:\bdo\s+not\b|\bmust\s+not\b|\bshould\s+not\b|"
        r"\bmay\s+not\b|\bcan\s+not\b|\bcannot\b|"
        r"\brather\s+than\b|"
        r"禁止|不得|不可|不要)"
    )
    weak_coordinated_negators = (
        r"(?:\bno\b|\bnot\b|\bnever\b|\bwithout\b)"
    )
    contrast_words = r"\b(?:but|however|instead|then|yet)\b"
    consumer_reuse = (
        r"\b(?:roster|codex|certificate|permit|egg|card|icon|"
        r"thumbnail|inventory|slot|ui)\b"
    )

    # Split on sentence/newline boundaries, but keep semicolon-separated
    # negative-list items together.  This makes
    # "Negative prompt: no crop. Crop from identity." inspect the second
    # sentence while still treating an entire "Avoid: a; b; c" list as
    # negative.
    source_to_output_patterns = (
        rf"\b(?:{protected_sources})\b[^,;]{{0,120}}"
        rf"\b(?:itself\s+)?(?:as|into)\s+"
        rf"(?:(?:the|this|a|an)\s+)?(?:final\s+)?"
        rf"(?:portrait|headshot|bust|output|result)\b",
        rf"\b(?:portrait|headshot|bust|output|result)\b"
        rf"[^,;]{{0,120}}\b(?:directly\s+)?from\s+"
        rf"(?:(?:the|this|a|an)\s+)?(?:{protected_sources})\b",
        rf"\b(?:{protected_sources})\b[^,;]{{0,120}}"
        rf"\bto\s+(?:create|make|become)\s+"
        rf"(?:(?:the|this|a|an)\s+)?(?:final\s+)?"
        rf"(?:portrait|headshot|bust|output|result)\b",
    )

    for sentence in re.split(r"[.!?\n]+", lowered):
        sentence = sentence.strip()
        if not sentence:
            continue
        negative_header = re.match(
            r"^(?:avoid|negative prompt|forbidden)\s*:",
            sentence,
        )
        segments = [part.strip() for part in sentence.split(";")]
        header_continuation = negative_header is not None
        if header_continuation:
            # Only the first semicolon item is governed unambiguously by the
            # negative-list header.  Later items must stand on their own;
            # otherwise "Negative prompt: no crop; then crop ..." becomes a
            # bypass.
            segments = segments[1:]
        for clause in segments:
            clause = re.sub(
                r"^(?:then|however|instead|but|yet)\b[:,]?\s*",
                "",
                clause,
            ).strip()
            if not clause:
                continue

            for relation_pattern in source_to_output_patterns:
                for relation in re.finditer(relation_pattern, clause):
                    relation_prefix = clause[: relation.start()][-80:]
                    if re.search(
                        rf"{local_negators}[^,;:]{{0,64}}$",
                        relation_prefix,
                    ):
                        continue
                    relation_text = relation.group(0)
                    if re.search(
                        rf"{local_negators}[^,;:]{{0,96}}"
                        rf"\b(?:{derivation_verbs})\b",
                        relation_text,
                    ):
                        # The protected source may occur at the end of a
                        # coordinated negative phrase:
                        # "portrait without a crop or trace from the
                        # identity board".  That is a prohibition, not an
                        # affirmative source-to-output instruction.
                        continue
                    return False

            for match in re.finditer(
                rf"\b(?:{derivation_verbs})\b",
                clause,
            ):
                prefix = clause[: match.start()]
                local_prefix = re.split(r"[,;:]", prefix)[-1][-64:]
                locally_negated = re.search(
                    rf"{local_negators}[^,;:]{{0,48}}$",
                    local_prefix,
                )
                if locally_negated is not None:
                    continue

                coordinated_prefix = prefix[-192:]
                strong_matches = list(
                    re.finditer(
                        strong_coordinated_negators,
                        coordinated_prefix,
                    )
                )
                if strong_matches:
                    tail = coordinated_prefix[
                        strong_matches[-1].end() :
                    ]
                    if (
                        not re.search(r"[;:]", tail)
                        and not re.search(contrast_words, tail)
                    ):
                        continue

                weak_matches = list(
                    re.finditer(
                        weak_coordinated_negators,
                        coordinated_prefix,
                    )
                )
                if weak_matches:
                    tail = coordinated_prefix[
                        weak_matches[-1].end() :
                    ]
                    first_item = tail.split(",", 1)[0]
                    if (
                        re.search(
                            rf"\b(?:{derivation_verbs})\b",
                            first_item,
                        )
                        and not re.search(r"[;:]", tail)
                        and not re.search(contrast_words, tail)
                    ):
                        continue

                verb = match.group(0)
                remaining = clause[match.start() :]
                if (
                    verb.startswith("zoom")
                    and re.match(r"zoomed[- ]out\b", remaining)
                    and re.search(
                        r"\b(?:composition|framing|centered|floating|bust|"
                        r"subject|silhouette|canvas)\b",
                        clause,
                    )
                    and not re.search(protected_sources, clause)
                ):
                    continue
                if (
                    verb == "cropped"
                    and (
                        header_continuation
                        or (
                            re.match(r"^constraints?\s*:", clause)
                            and re.search(
                                r"\bno\b",
                                clause[: match.start()],
                            )
                        )
                        or re.match(r"^no\b", clause)
                    )
                    and re.match(
                        r"cropped\s+(?:parts?|anatomy|features?|ears?|"
                        r"markings?|silhouette|chest|horn|armor|ring)\b",
                        remaining,
                    )
                ):
                    continue
                if (
                    verb.startswith("reus")
                    and re.search(consumer_reuse, clause)
                    and not re.search(protected_sources, clause)
                ):
                    continue
                # Any other unnegated derivation verb is fail-closed.  This
                # deliberately rejects indirect positives such as "allowed
                # to crop", "reframe the identity board", or "paste a
                # screenshot", not just imperative/modal grammar.
                return False
    return True


def _validate_catalog_binding(
    *,
    repo_root: Path,
    catalog_path: Path,
    form_id: str,
    pet_root: Path,
) -> str:
    catalog = _read_json_object(catalog_path, "pet_art_catalog")
    forms = catalog.get("forms")
    if not isinstance(forms, list):
        raise PortraitBuildError("pet_art_catalog.forms 必须是数组")
    matches = [
        form
        for form in forms
        if isinstance(form, dict) and form.get("formId") == form_id
    ]
    if len(matches) != 1:
        raise PortraitBuildError(
            f"pet_art_catalog 必须恰好声明一个 formId={form_id}，实际 {len(matches)}"
        )
    pet = matches[0].get("pet")
    if not isinstance(pet, dict) or not isinstance(pet.get("root"), str):
        raise PortraitBuildError(f"{form_id}.pet.root 缺失")
    declared_root = _resolve_inside(
        repo_root,
        Path(pet["root"]),
        f"{form_id}.pet.root",
    )
    if declared_root != pet_root:
        raise PortraitBuildError(
            f"formId/petRoot 与 pet_art_catalog 映射不一致："
            f"{repo_relative(declared_root, repo_root)} != "
            f"{repo_relative(pet_root, repo_root)}"
        )
    # Build-time binding permits the catalog's pre-publication state where
    # portraitPath is not installed yet.  If the field already exists it must
    # be exact; the release auditor always requires it.
    portrait_value = pet.get("portraitPath")
    if portrait_value is not None:
        if not isinstance(portrait_value, str):
            raise PortraitBuildError(
                f"{form_id}.pet.portraitPath 必须是字符串"
            )
        declared_portrait = _resolve_inside(
            repo_root,
            Path(portrait_value),
            f"{form_id}.pet.portraitPath",
        )
        expected_portrait = pet_root / RUNTIME_PATH
        if declared_portrait != expected_portrait.resolve():
            raise PortraitBuildError(
                f"{form_id}.pet.portraitPath 必须绑定固定 runtime："
                f"{repo_relative(expected_portrait, repo_root)}"
            )
    return repo_relative(catalog_path, repo_root)


def _validate_isolated_not_catalogued(
    *,
    repo_root: Path,
    catalog_path: Path,
    form_id: str,
    pet_root: Path,
) -> None:
    """Prevent ``--isolated`` from bypassing an existing formal mapping."""

    if not catalog_path.is_file():
        return
    catalog = _read_json_object(catalog_path, "pet_art_catalog")
    forms = catalog.get("forms")
    if not isinstance(forms, list):
        raise PortraitBuildError("pet_art_catalog.forms 必须是数组")
    for index, form in enumerate(forms):
        if not isinstance(form, dict):
            raise PortraitBuildError(
                f"pet_art_catalog.forms[{index}] 必须是对象"
            )
        catalog_form_id = form.get("formId")
        pet = form.get("pet")
        if not isinstance(catalog_form_id, str) or not isinstance(pet, dict):
            raise PortraitBuildError(
                f"pet_art_catalog.forms[{index}] 缺少 formId/pet"
            )
        root_value = pet.get("root")
        if not isinstance(root_value, str):
            raise PortraitBuildError(
                f"pet_art_catalog.forms[{index}].pet.root 缺失"
            )
        declared_root = _resolve_inside(
            repo_root,
            Path(root_value),
            f"pet_art_catalog.forms[{index}].pet.root",
        )
        if catalog_form_id == form_id or declared_root == pet_root:
            raise PortraitBuildError(
                "--isolated 不能绕过已存在的 formal catalog 映射："
                f"formId={catalog_form_id}, "
                f"petRoot={repo_relative(declared_root, repo_root)}"
            )


def _validate_generation_attestation(
    *,
    attestation: dict[str, Any],
    generation_id: str,
    input_path: Path,
    input_bytes: bytes,
    input_image: Image.Image,
    identity_reference: Path,
    identity_bytes: bytes,
    prompt_path: Path,
    prompt_bytes: bytes,
    repo_root: Path,
    pet_root: Path,
    form_id: str,
    catalog_path: Path,
    isolated: bool,
    key: tuple[int, int, int],
) -> None:
    result_record = attestation.get("generationResultEvidence")
    if not isinstance(result_record, dict) or not isinstance(
        result_record.get("path"),
        str,
    ):
        raise PortraitBuildError(
            "generation attestation 缺少外部 generationResultEvidence.path"
        )
    generation_result_evidence = _validate_generation_result_evidence(
        repo_root=repo_root,
        result_path=Path(result_record["path"]),
        generation_id=generation_id,
        input_path=input_path,
        prompt_path=prompt_path,
        identity_reference=identity_reference,
        pet_root=pet_root,
        form_id=form_id,
        isolated=isolated,
        key=key,
        catalog_path=catalog_path,
        expected_transcript_evidence=(
            result_record.get("transcriptEvidence")
            if isinstance(
                result_record.get("transcriptEvidence"),
                dict,
            )
            else None
        ),
        input_snapshot=input_bytes,
    )
    identity_evidence = _validate_identity_evidence(
        repo_root=repo_root,
        pet_root=pet_root,
        form_id=form_id,
        identity_reference=identity_reference,
        catalog_path=catalog_path,
        isolated=isolated,
    )
    expected = {
        "schemaVersion": GENERATION_ATTESTATION_SCHEMA_VERSION,
        "generator": "built_in_imagegen",
        "generationId": generation_id,
        "compositionClaim": "dedicated_headshot",
        "independentlyAuthoredClaim": True,
        "semanticIndependenceVerified": False,
        "ownerReviewStatus": "owner_review_pending",
        "releaseGate": False,
        "fullBodyCropAllowed": False,
        "claimLimit": (
            "project-directed generated candidate; automated checks do not "
            "prove semantic independence, copyright provenance, or owner "
            "approval"
        ),
        "sourceInputSha256": sha256_bytes(input_bytes),
        "sourceInputRgbaSha256": rgba_hash(input_image.convert("RGBA")),
        "identityReferencePath": repo_relative(identity_reference, repo_root),
        "identityReferenceSha256": sha256_bytes(identity_bytes),
        "promptSha256": sha256_bytes(prompt_bytes),
        "promptContract": "dedicated_headshot_not_full_body_crop_v1",
        "generationResultEvidence": generation_result_evidence,
        "identityEvidence": identity_evidence,
    }
    if set(attestation) != set(expected):
        missing = sorted(set(expected) - set(attestation))
        extra = sorted(set(attestation) - set(expected))
        raise PortraitBuildError(
            "generation attestation 字段集合不符合严格 schema："
            f"missing={missing}, extra={extra}"
        )
    for key, value in expected.items():
        if attestation.get(key) != value:
            raise PortraitBuildError(
                f"generation attestation 与当前输入绑定不一致：{key}"
            )


def _write_generation_attestation_pinned(
    options: GenerationAttestationOptions,
    *,
    pinned_repo_root: Path,
    repo_root_fd: int,
    pinned_pet_root: Path,
    pet_root_fd: int,
    pinned_output_path: Path,
    output_parent_fd: int,
) -> dict[str, Any]:
    """Create one strict, input-bound attestation without overwriting."""

    supplied_repo_root = options.repo_root.absolute()
    repo_root = pinned_repo_root
    if not repo_root.is_dir():
        raise PortraitBuildError(f"仓库目录不存在：{repo_root}")
    pet_root = _resolve_inside(
        supplied_repo_root,
        options.pet_root,
        "宠物资源根目录",
    )
    if pet_root != pinned_pet_root:
        raise PortraitBuildError(
            "宠物资源根目录与入口 pinned pet root 不一致"
        )
    if not pet_root.is_dir():
        raise PortraitBuildError(f"宠物资源根目录不存在：{pet_root}")
    if not FORM_ID_PATTERN.fullmatch(options.form_id):
        raise PortraitBuildError(
            "form-id 只能使用小写 ASCII 字母、数字和下划线"
        )
    generation_id = options.generation_id.strip()
    if not _valid_generation_id(generation_id):
        raise PortraitBuildError(
            "generation-id 必须是 call_<24 alnum> 或标准 exec UUID"
        )

    input_path = _resolve_inside(
        supplied_repo_root,
        options.input_path,
        "chroma 原图",
    )
    prompt_path = _resolve_inside(
        supplied_repo_root,
        options.prompt_path,
        "prompt",
    )
    generation_result_path = _resolve_inside(
        supplied_repo_root,
        options.generation_result,
        "ImageGen result evidence",
    )
    identity_reference = _resolve_inside(
        supplied_repo_root,
        options.identity_reference,
        "身份参考",
    )
    for path, label in (
        (input_path, "chroma 原图"),
        (prompt_path, "prompt"),
        (generation_result_path, "ImageGen result evidence"),
        (identity_reference, "身份参考"),
    ):
        if not path.is_file():
            raise PortraitBuildError(f"{label}不存在：{path}")
    input_bytes = _read_regular_file_snapshot(input_path, "chroma 原图")
    prompt_bytes = _read_regular_file_snapshot(prompt_path, "prompt")
    generation_result_bytes = _read_regular_file_snapshot(
        generation_result_path,
        "ImageGen result evidence",
    )
    identity_bytes = _read_regular_file_snapshot(
        identity_reference,
        "身份参考",
    )
    authority_snapshots = (
        (input_path, input_bytes, "chroma 原图"),
        (prompt_path, prompt_bytes, "prompt"),
        (
            generation_result_path,
            generation_result_bytes,
            "ImageGen result evidence",
        ),
        (identity_reference, identity_bytes, "身份参考"),
    )
    try:
        identity_reference.relative_to((pet_root / "identity").resolve())
    except ValueError as exc:
        raise PortraitBuildError(
            "identity reference 必须位于当前 petRoot/identity 内"
        ) from exc

    try:
        prompt_text = prompt_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PortraitBuildError(f"prompt 必须是 UTF-8 文本：{exc}") from exc
    if not prompt_text.strip():
        raise PortraitBuildError("prompt 文件不能为空")
    if not _prompt_declares_dedicated_no_crop(prompt_text):
        raise PortraitBuildError(
            "prompt 必须同时声明 dedicated headshot/portrait，"
            "并明确禁止从全身图裁切"
        )

    input_image, input_format, _ = _decode_image_snapshot(
        input_bytes,
        input_path,
        "chroma 原图",
    )
    if input_format != "PNG":
        raise PortraitBuildError(
            "built-in ImageGen 原始输出必须保持 PNG 字节"
        )
    if (
        input_image.width < MIN_SOURCE_SIZE
        or input_image.height < MIN_SOURCE_SIZE
    ):
        raise PortraitBuildError(
            "built-in imagegen chroma 原图每边至少 "
            f"{MIN_SOURCE_SIZE}px，实际 "
            f"{input_image.width}x{input_image.height}"
        )

    catalog_path = _resolve_inside(
        supplied_repo_root,
        options.catalog_path,
        "pet_art_catalog",
    )
    if options.isolated:
        _validate_isolated_not_catalogued(
            repo_root=repo_root,
            catalog_path=catalog_path,
            form_id=options.form_id,
            pet_root=pet_root,
        )
    else:
        _validate_catalog_binding(
            repo_root=repo_root,
            catalog_path=catalog_path,
            form_id=options.form_id,
            pet_root=pet_root,
        )

    generation_result_evidence = _validate_generation_result_evidence(
        repo_root=repo_root,
        result_path=generation_result_path,
        generation_id=generation_id,
        input_path=input_path,
        prompt_path=prompt_path,
        identity_reference=identity_reference,
        pet_root=pet_root,
        form_id=options.form_id,
        isolated=options.isolated,
        key=options.key,
        catalog_path=catalog_path,
        result_snapshot=generation_result_bytes,
        input_snapshot=input_bytes,
    )
    identity_evidence = _validate_identity_evidence(
        repo_root=repo_root,
        pet_root=pet_root,
        form_id=options.form_id,
        identity_reference=identity_reference,
        catalog_path=catalog_path,
        isolated=options.isolated,
    )

    output_path = _resolve_inside(
        supplied_repo_root,
        options.output_path,
        "generation attestation 输出",
    )
    if output_path != pinned_output_path:
        raise PortraitBuildError(
            "generation attestation 输出与入口 pinned path 不一致"
        )
    if output_path.suffix.casefold() != ".json":
        raise PortraitBuildError(
            "generation attestation 输出必须使用 .json 后缀"
        )
    try:
        output_path.relative_to((repo_root / ".run").resolve())
    except ValueError as exc:
        raise PortraitBuildError(
            "generation attestation 只能写入仓库 .run/ 隔离区"
        ) from exc
    if output_path in {
        input_path,
        prompt_path,
        generation_result_path,
        identity_reference,
    }:
        raise PortraitBuildError(
            "generation attestation 输出不得覆盖任一输入"
        )
    if output_path.exists() or output_path.is_symlink():
        raise PortraitBuildError(
            f"generation attestation 已存在，永久拒绝覆盖：{output_path}"
        )

    attestation = {
        "schemaVersion": GENERATION_ATTESTATION_SCHEMA_VERSION,
        "generator": "built_in_imagegen",
        "generationId": generation_id,
        "compositionClaim": "dedicated_headshot",
        "independentlyAuthoredClaim": True,
        "semanticIndependenceVerified": False,
        "ownerReviewStatus": "owner_review_pending",
        "releaseGate": False,
        "fullBodyCropAllowed": False,
        "claimLimit": (
            "project-directed generated candidate; automated checks do not "
            "prove semantic independence, copyright provenance, or owner "
            "approval"
        ),
        "sourceInputSha256": sha256_bytes(input_bytes),
        "sourceInputRgbaSha256": rgba_hash(input_image.convert("RGBA")),
        "identityReferencePath": repo_relative(
            identity_reference,
            repo_root,
        ),
        "identityReferenceSha256": sha256_bytes(identity_bytes),
        "promptSha256": sha256_bytes(prompt_bytes),
        "promptContract": "dedicated_headshot_not_full_body_crop_v1",
        "generationResultEvidence": generation_result_evidence,
        "identityEvidence": identity_evidence,
    }
    payload = (
        json.dumps(attestation, ensure_ascii=False, indent=2) + "\n"
    ).encode("utf-8")
    _assert_file_snapshots_unchanged(authority_snapshots)
    output_parent_relative = output_path.parent.relative_to(repo_root)
    _publish_with_pinned_parent_no_clobber(
        root_fd=repo_root_fd,
        pinned_parent_fd=output_parent_fd,
        parent_relative=output_parent_relative,
        filename=output_path.name,
        payload=payload,
        display_root=repo_root,
        label="generation attestation",
        absolute_bindings=(
            (
                repo_root,
                repo_root_fd,
                "generation attestation repo root",
            ),
            (
                pet_root,
                pet_root_fd,
                "generation attestation pet root",
            ),
        ),
    )
    return attestation


def write_generation_attestation(
    options: GenerationAttestationOptions,
) -> dict[str, Any]:
    """Pin repository and pet roots before validating any evidence paths."""

    supplied_repo_root = options.repo_root.absolute()
    repo_root = options.repo_root.resolve()
    if not repo_root.is_dir():
        raise PortraitBuildError(f"仓库目录不存在：{repo_root}")
    repo_root_fd = _open_absolute_directory(repo_root)
    try:
        pet_root = _resolve_inside(
            supplied_repo_root,
            options.pet_root,
            "宠物资源根目录",
        )
        pet_relative = pet_root.relative_to(repo_root)
        pet_root_fd = _open_directory_chain_from_fd(
            repo_root_fd,
            pet_relative,
            create=False,
            display_root=repo_root,
        )
        try:
            output_path = _resolve_inside(
                supplied_repo_root,
                options.output_path,
                "generation attestation 输出",
            )
            if output_path.suffix.casefold() != ".json":
                raise PortraitBuildError(
                    "generation attestation 输出必须使用 .json 后缀"
                )
            run_root = repo_root / ".run"
            try:
                output_path.relative_to(run_root)
            except ValueError as exc:
                raise PortraitBuildError(
                    "generation attestation 只能写入仓库 .run/ 隔离区"
                ) from exc
            output_parent_relative = output_path.parent.relative_to(
                repo_root
            )
            output_parent_fd = _open_directory_chain_from_fd(
                repo_root_fd,
                output_parent_relative,
                create=True,
                display_root=repo_root,
            )
            try:
                return _write_generation_attestation_pinned(
                    options,
                    pinned_repo_root=repo_root,
                    repo_root_fd=repo_root_fd,
                    pinned_pet_root=pet_root,
                    pet_root_fd=pet_root_fd,
                    pinned_output_path=output_path,
                    output_parent_fd=output_parent_fd,
                )
            finally:
                os.close(output_parent_fd)
        finally:
            os.close(pet_root_fd)
    finally:
        os.close(repo_root_fd)


