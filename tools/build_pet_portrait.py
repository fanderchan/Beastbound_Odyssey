def _closed_registration_tree_index(
    *,
    root: Path,
    repo_root: Path,
    expected: dict[str, dict[str, Any]],
    label: str,
) -> dict[str, dict[str, Any]]:
    """Replay one complete registration tree, ignoring only valid imports."""

    root = _resolve_inside(repo_root, root, label)
    if root.is_symlink() or not root.is_dir():
        raise PortraitBuildError(f"{label}必须是真实目录：{root}")
    actual: dict[str, dict[str, Any]] = {}
    expected_paths = frozenset(expected)
    expected_directories: set[str] = set()
    for path_value in expected_paths:
        parent = Path(path_value).parent
        while parent != Path("."):
            expected_directories.add(parent.as_posix())
            parent = parent.parent
    for current, directory_names, file_names in os.walk(
        root,
        followlinks=False,
    ):
        current_path = Path(current)
        for name in directory_names:
            child = current_path / name
            try:
                mode = child.lstat().st_mode
            except OSError as exc:
                raise PortraitBuildError(
                    f"无法检查{label}目录：{child}: {exc}"
                ) from exc
            if stat.S_ISLNK(mode) or not stat.S_ISDIR(mode):
                raise PortraitBuildError(
                    f"{label}包含不安全目录：{child}"
                )
            relative_directory = child.relative_to(root).as_posix()
            if relative_directory not in expected_directories:
                raise PortraitBuildError(
                    f"{label}包含未登记目录：{relative_directory}"
                )
        for name in file_names:
            child = current_path / name
            try:
                mode = child.lstat().st_mode
            except OSError as exc:
                raise PortraitBuildError(
                    f"无法检查{label}文件：{child}: {exc}"
                ) from exc
            if stat.S_ISLNK(mode) or not stat.S_ISREG(mode):
                raise PortraitBuildError(
                    f"{label}包含不安全文件：{child}"
                )
            relative = child.relative_to(root).as_posix()
            if relative.endswith(".import"):
                base_relative = relative[: -len(".import")]
                base = root / base_relative
                if (
                    base_relative not in expected_paths
                    or not base.is_file()
                    or base.is_symlink()
                ):
                    raise PortraitBuildError(
                        f"{label}包含孤立或未登记 .import：{relative}"
                    )
                continue
            payload = _read_regular_file_snapshot(
                child,
                f"{label}:{relative}",
            )
            actual[relative] = _closed_registration_record(
                relative,
                payload,
            )
    if actual != expected:
        missing = sorted(set(expected) - set(actual))
        extra = sorted(set(actual) - set(expected))
        drift = sorted(
            path_value
            for path_value in set(actual) & set(expected)
            if actual[path_value] != expected[path_value]
        )
        raise PortraitBuildError(
            f"{label}完整树与登记清单漂移："
            f"missing={missing[:10]} extra={extra[:10]} "
            f"changed={drift[:10]}"
        )
    return actual


def _closed_registration_json_value_at(
    value: Any,
    field_path: tuple[str, ...],
) -> Any:
    current = value
    for key in field_path:
        if not isinstance(current, dict) or key not in current:
            return None
        current = current[key]
    return current


def _closed_registration_set_json_value(
    value: dict[str, Any],
    field_path: tuple[str, ...],
    replacement: str,
) -> None:
    current = value
    for key in field_path[:-1]:
        child = current.get(key)
        if not isinstance(child, dict):
            raise PortraitBuildError(
                "fusion pet closed-registration integrity field "
                f"不是对象路径：{'.'.join(field_path)}"
            )
        current = child
    current[field_path[-1]] = replacement


def _closed_registration_replay_json_transform(
    *,
    source_payload: bytes,
    candidate_payload: bytes,
    updates: tuple[tuple[tuple[str, ...], str, str], ...],
    label: str,
) -> None:
    try:
        source_text = source_payload.decode("utf-8")
        candidate_text = candidate_payload.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PortraitBuildError(
            f"{label}必须是 UTF-8 JSON：{exc}"
        ) from exc
    source_value = _strict_json_object_text(source_text, f"{label} source")
    candidate_value = _strict_json_object_text(
        candidate_text,
        f"{label} candidate",
    )
    expected_candidate = copy.deepcopy(source_value)
    replayed_text = source_text
    for field_path, source_digest, candidate_digest in updates:
        if (
            _closed_registration_json_value_at(source_value, field_path)
            != source_digest
        ):
            raise PortraitBuildError(
                f"{label} source 未绑定 {'.'.join(field_path)}"
            )
        old_token = json.dumps(source_digest, ensure_ascii=False)
        new_token = json.dumps(candidate_digest, ensure_ascii=False)
        if source_text.count(old_token) != 1:
            raise PortraitBuildError(
                f"{label} source hash token 不唯一："
                f"{'.'.join(field_path)}"
            )
        replayed_text = replayed_text.replace(old_token, new_token, 1)
        _closed_registration_set_json_value(
            expected_candidate,
            field_path,
            candidate_digest,
        )
    if replayed_text.encode("utf-8") != candidate_payload:
        raise PortraitBuildError(
            f"{label} candidate 字节不是 source 的精确声明变换"
        )
    if candidate_value != expected_candidate:
        raise PortraitBuildError(
            f"{label} candidate 修改了声明字段以外内容"
        )


def _closed_registration_pipeline_replay_sha256(
    payload: bytes,
    *,
    raw_source: Path,
    label: str,
) -> str:
    try:
        text = payload.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise PortraitBuildError(
            f"{label}必须是 UTF-8 JSON：{exc}"
        ) from exc
    metadata = _strict_json_object_text(text, label)
    metadata["input"] = str(raw_source.resolve())
    replay_payload = (
        json.dumps(
            metadata,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        )
        + "\n"
    ).encode("utf-8")
    return sha256_bytes(replay_payload)


def _closed_registration_scalar_paths(
    value: Any,
    expected: str,
    path: tuple[str, ...] = (),
) -> tuple[tuple[str, ...], ...]:
    matches: list[tuple[str, ...]] = []
    if isinstance(value, dict):
        for key, child in value.items():
            matches.extend(
                _closed_registration_scalar_paths(
                    child,
                    expected,
                    (*path, str(key)),
                )
            )
    elif isinstance(value, list):
        for index, child in enumerate(value):
            matches.extend(
                _closed_registration_scalar_paths(
                    child,
                    expected,
                    (*path, f"[{index}]"),
                )
            )
    elif value == expected:
        matches.append(path)
    return tuple(matches)


def _closed_registration_hash_references(
    *,
    root: Path,
    records: dict[str, dict[str, Any]],
    expected_hash: str,
    label: str,
) -> frozenset[tuple[str, tuple[str, ...]]]:
    token = expected_hash.encode("ascii")
    references: set[tuple[str, tuple[str, ...]]] = set()
    for relative in records:
        payload = _read_regular_file_snapshot(
            root / relative,
            f"{label}:{relative}",
        )
        if token not in payload:
            continue
        if Path(relative).suffix.lower() != ".json":
            references.add((relative, ("$raw",)))
            continue
        try:
            text = payload.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise PortraitBuildError(
                f"{label}:{relative} 必须是 UTF-8 JSON：{exc}"
            ) from exc
        parsed = _strict_json_object_text(text, f"{label}:{relative}")
        scalar_paths = _closed_registration_scalar_paths(
            parsed,
            expected_hash,
        )
        if not scalar_paths:
            references.add((relative, ("$raw",)))
            continue
        references.update(
            (relative, field_path) for field_path in scalar_paths
        )
    return frozenset(references)


