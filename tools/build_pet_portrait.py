def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def parse_hex_color(value: str) -> tuple[int, int, int]:
    text = value.strip().lstrip("#")
    if not re.fullmatch(r"[0-9A-Fa-f]{6}", text):
        raise argparse.ArgumentTypeError("颜色必须是六位十六进制 RGB")
    return tuple(int(text[index : index + 2], 16) for index in (0, 2, 4))


def color_text(value: tuple[int, int, int]) -> str:
    return "#" + "".join(f"{channel:02X}" for channel in value)


def _resolve_inside(root: Path, path: Path, label: str) -> Path:
    supplied_root = root.absolute()
    root = root.resolve()
    lexical = path if path.is_absolute() else supplied_root / path
    lexical = lexical.absolute()
    if lexical.is_symlink():
        raise PortraitBuildError(f"{label}路径不得包含符号链接：{lexical}")
    try:
        supplied_relative = lexical.relative_to(supplied_root)
    except ValueError:
        supplied_relative = None
    if supplied_relative is not None:
        current = supplied_root
        for part in supplied_relative.parts:
            current = current / part
            if current.is_symlink():
                raise PortraitBuildError(
                    f"{label}路径不得包含符号链接：{current}"
                )
    candidate = lexical.resolve()
    try:
        relative = candidate.relative_to(root)
    except ValueError as exc:
        raise PortraitBuildError(f"{label}必须位于仓库内：{candidate}") from exc
    current = root
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise PortraitBuildError(f"{label}路径不得包含符号链接：{current}")
    return candidate


