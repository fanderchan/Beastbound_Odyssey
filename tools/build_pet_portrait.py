def _reject_symlink_components(path: Path, label: str) -> None:
    lexical = path.absolute()
    current = Path(lexical.anchor)
    for part in lexical.parts[1:]:
        current = current / part
        if current.is_symlink():
            raise PortraitBuildError(
                f"{label}路径不得包含符号链接：{current}"
            )


def _resolve_imagegen_cache_source(
    path_text: str,
    *,
    repo_root: Path,
) -> Path:
    lexical = Path(path_text).expanduser()
    if not lexical.is_absolute():
        raise PortraitBuildError(
            "ImageGen result evidence 的 generator source 必须是绝对路径"
        )
    lexical = lexical.absolute()
    _reject_symlink_components(lexical, "ImageGen generator source")
    try:
        resolved = lexical.resolve(strict=True)
    except OSError as exc:
        raise PortraitBuildError(
            f"ImageGen generator source 不存在：{lexical}: {exc}"
        ) from exc
    if not resolved.is_file():
        raise PortraitBuildError(
            f"ImageGen generator source 不是普通文件：{resolved}"
        )
    try:
        resolved.relative_to(repo_root.resolve())
    except ValueError:
        pass
    else:
        raise PortraitBuildError(
            "ImageGen generator source 必须独立于仓库工作区，"
            "不能由 attestation writer 在 .run 内自证"
        )
    codex_home_lexical = _canonical_codex_home().absolute()
    _reject_symlink_components(codex_home_lexical, "Codex state root")
    try:
        codex_home = codex_home_lexical.resolve(strict=True)
        cache_root_lexical = codex_home_lexical / "generated_images"
        _reject_symlink_components(
            cache_root_lexical,
            "Codex generated image cache",
        )
        cache_root = cache_root_lexical.resolve(strict=True)
    except OSError as exc:
        raise PortraitBuildError(
            f"Codex generated image cache 不存在：{exc}"
        ) from exc
    try:
        cache_root.relative_to(codex_home)
        cache_relative = resolved.relative_to(cache_root)
    except ValueError as exc:
        raise PortraitBuildError(
            "ImageGen generator source 必须精确来自真实 "
            "Path.home()/.codex/generated_images"
        ) from exc
    if len(cache_relative.parts) != 2:
        raise PortraitBuildError(
            "ImageGen generator source 必须使用 "
            "generated_images/<session-uuid>/<generation-id>.png"
        )
    session_id = cache_relative.parts[0]
    if not SESSION_ID_PATTERN.fullmatch(session_id):
        raise PortraitBuildError(
            "ImageGen generator source 的 session 目录不是标准 UUID"
        )
    if resolved.suffix.casefold() != ".png":
        raise PortraitBuildError(
            "ImageGen generator source 必须是原始 PNG"
        )
    return resolved


