def _atomic_write_relative_no_clobber(
    root_fd: int,
    relative: Path,
    payload: bytes,
    *,
    display_root: Path,
    label: str,
    create_parents: bool,
) -> None:
    """Atomically publish bytes relative to one held, trusted root fd."""

    if (
        relative.is_absolute()
        or ".." in relative.parts
        or relative.name in {"", ".", ".."}
    ):
        raise PortraitBuildError(
            f"{label}输出路径非法：{relative}"
        )
    parent_fd = _open_directory_chain_from_fd(
        root_fd,
        relative.parent,
        create=create_parents,
        display_root=display_root,
    )
    staged_name: str | None = None
    staged_fd: int | None = None
    published = False
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    try:
        if (
            _relative_file_stat(
                parent_fd,
                Path(relative.name),
                display_root=display_root / relative.parent,
            )
            is not None
        ):
            raise PortraitBuildError(
                f"{label}已存在，永久拒绝覆盖："
                f"{display_root / relative}"
            )
        for _ in range(128):
            candidate = (
                f".{relative.name}.{secrets.token_hex(12)}.tmp"
            )
            try:
                staged_fd = os.open(
                    candidate,
                    flags,
                    0o600,
                    dir_fd=parent_fd,
                )
            except FileExistsError:
                continue
            staged_name = candidate
            break
        if staged_fd is None or staged_name is None:
            raise PortraitBuildError(
                f"{label}无法创建安全临时文件"
            )
        with os.fdopen(staged_fd, "wb") as handle:
            staged_fd = None
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        try:
            os.link(
                staged_name,
                relative.name,
                src_dir_fd=parent_fd,
                dst_dir_fd=parent_fd,
                follow_symlinks=False,
            )
        except FileExistsError as exc:
            raise PortraitBuildError(
                f"{label}被并发创建，拒绝覆盖"
            ) from exc
        published = True
        os.fsync(parent_fd)
    except Exception as exc:
        if published:
            rollback_failure: str | None = None
            try:
                published_stat = os.stat(
                    relative.name,
                    dir_fd=parent_fd,
                    follow_symlinks=False,
                )
                if (
                    not stat.S_ISREG(published_stat.st_mode)
                    or _sha256_relative_file(
                        parent_fd,
                        Path(relative.name),
                        display_root=display_root / relative.parent,
                    )
                    != sha256_bytes(payload)
                ):
                    rollback_failure = (
                        "published name changed before rollback"
                    )
                else:
                    os.unlink(relative.name, dir_fd=parent_fd)
                    os.fsync(parent_fd)
            except (OSError, PortraitBuildError) as cleanup:
                rollback_failure = str(cleanup)
            if rollback_failure is not None:
                raise PortraitBuildError(
                    f"{label}发布失败且安全回滚不完整："
                    f"{rollback_failure}"
                ) from exc
        raise
    finally:
        if staged_fd is not None:
            os.close(staged_fd)
        if staged_name is not None:
            try:
                os.unlink(staged_name, dir_fd=parent_fd)
            except FileNotFoundError:
                pass
        os.close(parent_fd)


