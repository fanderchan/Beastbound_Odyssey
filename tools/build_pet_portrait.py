def _find_codex_rollout_transcript(session_id: str) -> Path:
    codex_home_lexical = _canonical_codex_home().absolute()
    candidates: list[Path] = []
    sessions = codex_home_lexical / "sessions"
    if sessions.is_dir():
        candidates.extend(
            path
            for path in sessions.glob(
                f"*/*/*/rollout-*-{session_id}.jsonl"
            )
            if path.is_file()
        )
    archived = codex_home_lexical / "archived_sessions"
    if archived.is_dir():
        candidates.extend(
            path
            for path in archived.glob(
                f"rollout-*-{session_id}.jsonl"
            )
            if path.is_file()
        )
    unique: dict[str, Path] = {}
    for path in candidates:
        _reject_symlink_components(path, "Codex rollout transcript")
        try:
            resolved = path.resolve(strict=True)
        except OSError as exc:
            raise PortraitBuildError(
                f"Codex rollout transcript 不可解析：{path}: {exc}"
            ) from exc
        unique[str(resolved)] = resolved
    if len(unique) != 1:
        raise PortraitBuildError(
            "ImageGen cache session 必须唯一映射一份真实 Codex rollout "
            f"transcript，实际 {len(unique)} 份：{session_id}"
        )
    return next(iter(unique.values()))


