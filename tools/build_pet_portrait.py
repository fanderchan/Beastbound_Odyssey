def _validate_codex_imagegen_transcript(
    *,
    generator_source: Path,
    generation_id: str,
    repo_root: Path,
    pet_root: Path,
    form_id: str,
    identity_reference: Path,
    prompt_path: Path,
    selected_entry: dict[str, Any],
    expected: dict[str, Any] | None = None,
) -> dict[str, Any]:
    session_id = generator_source.parent.name
    transcript = _find_codex_rollout_transcript(session_id)
    with transcript.open("rb") as handle:
        first_raw = handle.readline(1024 * 1024 + 1)
    if not first_raw or len(first_raw) > 1024 * 1024:
        raise PortraitBuildError(
            "Codex rollout transcript 首条 session_meta 缺失或过大"
        )
    first_raw = first_raw.rstrip(b"\r\n")
    first_record = _decode_json_record(first_raw, "Codex session_meta")
    first_payload = first_record.get("payload")
    if (
        first_record.get("type") != "session_meta"
        or not isinstance(first_payload, dict)
        or first_payload.get("id") != session_id
    ):
        raise PortraitBuildError(
            "Codex rollout transcript 首条 session_meta.id "
            "与 generator cache session 不一致"
        )

    generator_bytes = generator_source.read_bytes()
    if not generator_bytes.startswith(b"\x89PNG\r\n\x1a\n"):
        raise PortraitBuildError(
            "canonical ImageGen cache 不是原始 PNG bytes"
        )
    if OPENAI_C2PA_MARKER not in generator_bytes:
        raise PortraitBuildError(
            "canonical ImageGen cache 缺少 OpenAI C2PA claim marker；"
            "该 marker 仅作辅助完整性检查，不代表已验证数字签名"
        )

    request_offset: int | None = None
    request_hash: str | None = None
    request_binding: dict[str, Any]
    if expected is not None:
        if expected.get("transcriptPath") != _codex_relative(transcript):
            raise PortraitBuildError(
                "generation attestation 的 Codex transcript path 漂移"
            )
        if expected.get("sessionId") != session_id:
            raise PortraitBuildError(
                "generation attestation 的 Codex session id 漂移"
            )
        event_offset = expected.get("eventByteOffset")
        event_raw = _read_transcript_line_at(transcript, event_offset)
        if sha256_bytes(event_raw) != expected.get("eventRecordSha256"):
            raise PortraitBuildError(
                "generation attestation 的 Codex event record 漂移"
            )
        if generation_id.startswith("call_"):
            request_offset = expected.get("requestByteOffset")
            request_raw = _read_transcript_line_at(
                transcript,
                request_offset,
            )
            request_hash, request_binding = (
                _validate_direct_imagegen_request_record(
                    request_raw,
                    generation_id,
                    repo_root=repo_root,
                    pet_root=pet_root,
                    form_id=form_id,
                    identity_reference=identity_reference,
                    prompt_path=prompt_path,
                    selected_entry=selected_entry,
                )
            )
            if request_hash != expected.get("requestRecordSha256"):
                raise PortraitBuildError(
                    "generation attestation 的 ImageGen request record 漂移"
                )
        else:
            request_binding = _unverified_exec_request_binding(
                form_id=form_id,
                prompt_path=prompt_path,
                repo_root=repo_root,
                selected_entry=selected_entry,
            )
    else:
        matching_event_offsets: set[int] = set()
        matching_request_offsets: set[int] = set()
        needle = generation_id.encode("ascii")
        with transcript.open("rb") as handle:
            with mmap.mmap(
                handle.fileno(),
                length=0,
                access=mmap.ACCESS_READ,
            ) as mapped:
                cursor = 0
                seen_line_offsets: set[int] = set()
                while True:
                    found = mapped.find(needle, cursor)
                    if found < 0:
                        break
                    line_start = mapped.rfind(b"\n", 0, found) + 1
                    cursor = found + len(needle)
                    if line_start in seen_line_offsets:
                        continue
                    seen_line_offsets.add(line_start)
                    line_end = mapped.find(b"\n", found)
                    if line_end < 0:
                        line_end = len(mapped)
                    if line_end - line_start > 32 * 1024 * 1024:
                        raise PortraitBuildError(
                            "Codex transcript candidate record 超过 32 MiB"
                        )
                    raw = bytes(mapped[line_start:line_end]).rstrip(b"\r")
                    try:
                        record = json.loads(raw)
                    except (UnicodeDecodeError, json.JSONDecodeError):
                        continue
                    if not isinstance(record, dict):
                        continue
                    payload = record.get("payload")
                    if not isinstance(payload, dict):
                        continue
                    if (
                        record.get("type") == "event_msg"
                        and payload.get("type") == "image_generation_end"
                        and payload.get("call_id") == generation_id
                    ):
                        matching_event_offsets.add(line_start)
                    if (
                        record.get("type") == "response_item"
                        and payload.get("type") == "function_call"
                        and payload.get("namespace") == "image_gen"
                        and payload.get("name") == "imagegen"
                        and payload.get("call_id") == generation_id
                    ):
                        matching_request_offsets.add(line_start)
        if len(matching_event_offsets) != 1:
            raise PortraitBuildError(
                "Codex transcript 必须恰好存在一条结构化 "
                f"image_generation_end，实际 {len(matching_event_offsets)}"
            )
        event_offset = next(iter(matching_event_offsets))
        event_raw = _read_transcript_line_at(transcript, event_offset)
        if generation_id.startswith("call_"):
            if len(matching_request_offsets) != 1:
                raise PortraitBuildError(
                    "direct ImageGen call 必须恰好存在一条结构化 "
                    f"function_call，实际 {len(matching_request_offsets)}"
                )
            request_offset = next(iter(matching_request_offsets))
            request_raw = _read_transcript_line_at(
                transcript,
                request_offset,
            )
            request_hash, request_binding = (
                _validate_direct_imagegen_request_record(
                    request_raw,
                    generation_id,
                    repo_root=repo_root,
                    pet_root=pet_root,
                    form_id=form_id,
                    identity_reference=identity_reference,
                    prompt_path=prompt_path,
                    selected_entry=selected_entry,
                )
            )
        else:
            request_binding = _unverified_exec_request_binding(
                form_id=form_id,
                prompt_path=prompt_path,
                repo_root=repo_root,
                selected_entry=selected_entry,
            )

    event_binding = _validate_imagegen_end_record(
        raw=event_raw,
        generation_id=generation_id,
        generator_source=generator_source,
        generator_bytes=generator_bytes,
    )
    evidence = {
        "contract": "codex_imagegen_rollout_event_binding_v2",
        "sessionId": session_id,
        "transcriptPath": _codex_relative(transcript),
        "sessionMetaRecordSha256": sha256_bytes(first_raw),
        "requestByteOffset": request_offset,
        "requestRecordSha256": request_hash,
        "requestArgumentBinding": request_binding,
        "eventByteOffset": event_offset,
        **event_binding,
        "importGateOnly": True,
        "portableReleaseAuditRequiresPrivateTranscript": False,
        "c2paOpenAiClaimMarkerPresent": True,
        "c2paSignatureCryptographicallyVerified": False,
    }
    if expected is not None and evidence != expected:
        raise PortraitBuildError(
            "generation attestation 的 Codex ImageGen transcript "
            "binding 不一致"
        )
    return evidence


def _validate_selected_source_manifest(
    *,
    repo_root: Path,
    pet_root: Path,
    form_id: str,
    input_path: Path,
    prompt_path: Path,
    result_path: Path,
    generation_id: str,
    isolated: bool,
    key: tuple[int, int, int],
    catalog_path: Path,
) -> tuple[dict[str, Any], dict[str, Any]]:
    manifest_path = _resolve_inside(
        repo_root,
        SELECTED_SOURCES_PATH,
        "portrait selected-sources manifest",
    )
    manifest = _read_json_object(
        manifest_path,
        "portrait selected-sources manifest",
    )
    if manifest.get("schemaVersion") != 1:
        raise PortraitBuildError(
            "portrait selected-sources manifest schemaVersion 必须为 1"
        )
    if manifest.get("catalog") != repo_relative(
        catalog_path,
        repo_root,
    ):
        raise PortraitBuildError(
            "portrait selected-sources manifest catalog 漂移"
        )
    entries = manifest.get("entries")
    if not isinstance(entries, list):
        raise PortraitBuildError(
            "portrait selected-sources manifest.entries 必须是数组"
        )
    matches = [
        entry
        for entry in entries
        if isinstance(entry, dict) and entry.get("formId") == form_id
    ]
    if len(matches) != 1:
        raise PortraitBuildError(
            "portrait selected-sources manifest 必须恰好选择一个 "
            f"formId={form_id}"
        )
    entry = matches[0]
    expected = {
        "formId": form_id,
        "petRoot": repo_relative(pet_root, repo_root),
        "input": repo_relative(input_path, repo_root),
        "prompt": repo_relative(prompt_path, repo_root),
        "result": repo_relative(result_path, repo_root),
        "generationId": generation_id,
        "key": color_text(key).lstrip("#"),
        "isolated": isolated,
    }
    allowed_fields = set(expected) | {
        "actualRequestPrompt",
        "requestArgumentCompatibility",
    }
    if set(entry) - allowed_fields:
        raise PortraitBuildError(
            "portrait selected-sources manifest entry 包含未知字段："
            f"{sorted(set(entry) - allowed_fields)}"
        )
    for field, expected_value in expected.items():
        actual = entry.get(field)
        if field == "key" and isinstance(actual, str):
            actual = actual.lstrip("#").upper()
        if actual != expected_value:
            raise PortraitBuildError(
                "portrait selected-sources manifest 最终选择不一致："
                f"{field}"
            )
    manifest_bytes = manifest_path.read_bytes()
    return (
        {
            "contract": "portrait_selected_sources_entry_v1",
            "path": repo_relative(manifest_path, repo_root),
            "sha256": sha256_bytes(manifest_bytes),
            "entrySha256": _canonical_json_sha256(entry),
        },
        entry,
    )


def _validate_generation_result_evidence(
    *,
    repo_root: Path,
    result_path: Path,
    generation_id: str,
    input_path: Path,
    prompt_path: Path,
    identity_reference: Path,
    pet_root: Path,
    form_id: str,
    isolated: bool,
    key: tuple[int, int, int],
    catalog_path: Path,
    expected_transcript_evidence: dict[str, Any] | None = None,
    result_snapshot: bytes | None = None,
    input_snapshot: bytes | None = None,
) -> dict[str, Any]:
    result_path = _resolve_inside(
        repo_root,
        result_path,
        "ImageGen result evidence",
    )
    if result_path.suffix.casefold() != ".txt":
        raise PortraitBuildError(
            "ImageGen result evidence 必须是独立的 UTF-8 .txt 文件"
        )
    try:
        result_path.relative_to((repo_root / ".run").resolve())
    except ValueError as exc:
        raise PortraitBuildError(
            "ImageGen result evidence 必须位于仓库 .run/ 隔离区"
        ) from exc
    if not result_path.is_file():
        raise PortraitBuildError(
            f"ImageGen result evidence 不存在：{result_path}"
        )
    result_bytes = (
        result_snapshot
        if result_snapshot is not None
        else result_path.read_bytes()
    )
    fields = _parse_generation_result_fields(result_bytes)

    generator_source_text = _one_generation_result_value(
        fields,
        (
            "selectedgeneratorresultpath",
            "selectedgeneratedsource",
            "generatorresultpath",
            "generatorsource",
            "generatedsource",
            "acceptedgeneratedsource",
            "rawsource",
            "resultpath",
            "selectedresultpath",
        ),
        "selected generator source path",
    )
    assert generator_source_text is not None
    generator_source = _resolve_imagegen_cache_source(
        generator_source_text,
        repo_root=repo_root,
    )

    explicit_generation_id = _one_generation_result_value(
        fields,
        (
            "selectedgeneratorresultid",
            "selectedgenerationid",
            "selectedresultid",
            "generatorresultid",
            "generatorcallid",
            "generationresultid",
            "resultid",
        ),
        "selected generation id",
        required=False,
    )
    selected_generation_id = (
        explicit_generation_id or generator_source.stem
    )
    if not _valid_generation_id(selected_generation_id):
        raise PortraitBuildError(
            "ImageGen result evidence 的 selected generation id 非法"
        )
    if selected_generation_id != generation_id:
        raise PortraitBuildError(
            "ImageGen result evidence 的 selected generation id "
            "与 --generation-id 不一致"
        )
    if generator_source.stem != generation_id:
        raise PortraitBuildError(
            "ImageGen generator source 文件名未绑定 selected generation id"
        )

    workspace_output_text = _one_generation_result_value(
        fields,
        (
            "workspacerawpath",
            "workspacecandidate",
            "copiedrawpath",
            "savedrawpath",
            "selectedrawpath",
            "rawpath",
            "workspaceraw",
            "selectedoutput",
            "output",
            "raw",
        ),
        "selected workspace output path",
    )
    assert workspace_output_text is not None
    workspace_output = _resolve_inside(
        repo_root,
        Path(workspace_output_text),
        "ImageGen result selected workspace output",
    )
    if workspace_output != input_path.resolve():
        raise PortraitBuildError(
            "ImageGen result evidence 的 selected workspace output "
            "未绑定当前 --input"
        )

    declared_output_hash = _one_generation_result_value(
        fields,
        (
            "sha256",
            "rawsha256",
            "selectedoutputsha256",
        ),
        "selected output SHA-256",
        required=False,
    )
    byte_parity_claim = _one_generation_result_value(
        fields,
        ("byteparitywithgeneratorsource",),
        "byte parity claim",
        required=False,
    )
    if declared_output_hash is None and (
        byte_parity_claim is None
        or byte_parity_claim.casefold() != "true"
    ):
        raise PortraitBuildError(
            "ImageGen result evidence 必须声明 selected output SHA-256，"
            "或显式声明 byteParityWithGeneratorSource=true"
        )
    input_hash = (
        sha256_bytes(input_snapshot)
        if input_snapshot is not None
        else sha256_file(input_path)
    )
    if declared_output_hash is not None:
        declared_output_hash = declared_output_hash.casefold()
        if not SHA256_PATTERN.fullmatch(declared_output_hash):
            raise PortraitBuildError(
                "ImageGen result evidence 的 selected output SHA-256 非法"
            )
        if declared_output_hash != input_hash:
            raise PortraitBuildError(
                "ImageGen result evidence 的 selected output SHA-256 "
                "与当前 --input 不一致"
            )
    generator_hash = sha256_file(generator_source)
    input_size = (
        len(input_snapshot)
        if input_snapshot is not None
        else input_path.stat().st_size
    )
    if generator_source.stat().st_size != input_size or (
        generator_hash != input_hash
    ):
        raise PortraitBuildError(
            "当前 --input 与独立 ImageGen generator source 不是逐字节同一输出"
        )

    declared_form_id = _one_generation_result_value(
        fields,
        ("formid", "petid"),
        "formId",
        required=False,
    )
    if declared_form_id is not None and declared_form_id != form_id:
        raise PortraitBuildError(
            "ImageGen result evidence 的 formId 与当前 form-id 不一致"
        )
    if declared_form_id is None and result_path.parent.name != form_id:
        raise PortraitBuildError(
            "未显式声明 formId 的 ImageGen result evidence "
            "必须位于同名 form 目录"
        )

    descriptor_keys = (
        "generator",
        "tool",
        "toolmode",
        "generationmode",
        "productionpath",
    )
    descriptors = [
        value
        for key in descriptor_keys
        for value in fields.get(key, ())
    ]
    if descriptors:
        normalized_descriptors = [
            re.sub(r"[^a-z0-9]", "", value.casefold())
            for value in descriptors
        ]
        if not any(
            "builtinimagegen" in value
            for value in normalized_descriptors
        ):
            raise PortraitBuildError(
                "ImageGen result evidence 未声明 built-in imagegen"
            )

    selection_evidence, selected_entry = (
        _validate_selected_source_manifest(
        repo_root=repo_root,
        pet_root=pet_root,
        form_id=form_id,
        input_path=input_path,
        prompt_path=prompt_path,
        result_path=result_path,
        generation_id=generation_id,
        isolated=isolated,
        key=key,
        catalog_path=catalog_path,
        )
    )
    transcript_evidence = _validate_codex_imagegen_transcript(
        generator_source=generator_source,
        generation_id=generation_id,
        repo_root=repo_root,
        pet_root=pet_root,
        form_id=form_id,
        identity_reference=identity_reference,
        prompt_path=prompt_path,
        selected_entry=selected_entry,
        expected=expected_transcript_evidence,
    )

    return {
        "contract": "built_in_imagegen_operational_binding_v2",
        "path": repo_relative(result_path, repo_root),
        "sha256": sha256_bytes(result_bytes),
        "selectedGenerationId": generation_id,
        "selectedOutputPath": repo_relative(input_path, repo_root),
        "selectedOutputSha256": input_hash,
        "declaredOutputSha256": declared_output_hash,
        "generatorSource": _generated_source_label(generator_source),
        "generatorSourceSha256": generator_hash,
        "byteParityVerified": True,
        "selectionEvidence": selection_evidence,
        "transcriptEvidence": transcript_evidence,
        "claimLimit": (
            "operational cache, rollout event, byte parity, and auxiliary "
            "C2PA marker binding; does not prove semantic independence, "
            "copyright provenance, or owner approval"
        ),
    }


def _resolve_pet_relative_path(
    pet_root: Path,
    value: str,
    label: str,
) -> Path:
    path = _resolve_inside(pet_root, Path(value), label)
    try:
        path.relative_to(pet_root.resolve())
    except ValueError as exc:
        raise PortraitBuildError(
            f"{label} 必须位于当前 pet root 内"
        ) from exc
    return path


def _formal_catalog_form(
    *,
    repo_root: Path,
    catalog_path: Path,
    form_id: str,
) -> dict[str, Any]:
    catalog = _read_json_object(catalog_path, "pet_art_catalog")
    forms = catalog.get("forms")
    if not isinstance(forms, list):
        raise PortraitBuildError("pet_art_catalog.forms 必须是数组")
    matches = [
        form
        for form in forms
        if isinstance(form, dict) and form.get("formId") == form_id
    ]
    if len(matches) != 1:
        raise PortraitBuildError(
            f"pet_art_catalog 必须恰好声明一个 formId={form_id}"
        )
    selected = matches[0]
    selected_pet = selected.get("pet")
    if not isinstance(selected_pet, dict) or not isinstance(
        selected_pet.get("root"),
        str,
    ):
        raise PortraitBuildError(f"{form_id}.pet.root 缺失")
    selected_root = _resolve_inside(
        repo_root,
        Path(selected_pet["root"]),
        f"{form_id}.pet.root",
    )
    root_matches = 0
    for index, form in enumerate(forms):
        if not isinstance(form, dict):
            continue
        pet = form.get("pet")
        root_value = pet.get("root") if isinstance(pet, dict) else None
        if not isinstance(root_value, str):
            continue
        candidate_root = _resolve_inside(
            repo_root,
            Path(root_value),
            f"pet_art_catalog.forms[{index}].pet.root",
        )
        if candidate_root == selected_root:
            root_matches += 1
    if root_matches != 1:
        raise PortraitBuildError(
            "pet_art_catalog identity root 必须全局唯一："
            f"{selected_pet['root']}"
        )
    return selected


