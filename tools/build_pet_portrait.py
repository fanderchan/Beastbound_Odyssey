def _read_transcript_line_at(
    transcript: Path,
    offset: int,
) -> bytes:
    if not isinstance(offset, int) or offset < 0:
        raise PortraitBuildError("Codex transcript event offset 非法")
    with transcript.open("rb") as handle:
        handle.seek(offset)
        raw = handle.readline(32 * 1024 * 1024 + 1)
    if not raw or len(raw) > 32 * 1024 * 1024:
        raise PortraitBuildError(
            "Codex transcript evidence 行不存在或超过 32 MiB"
        )
    return raw.rstrip(b"\r\n")


def _decode_json_record(raw: bytes, label: str) -> dict[str, Any]:
    try:
        value = json.loads(raw)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise PortraitBuildError(
            f"{label}不是合法 JSON record：{exc}"
        ) from exc
    if not isinstance(value, dict):
        raise PortraitBuildError(f"{label}必须是 JSON object record")
    return value


def _validate_imagegen_end_record(
    *,
    raw: bytes,
    generation_id: str,
    generator_source: Path,
    generator_bytes: bytes,
) -> dict[str, Any]:
    record = _decode_json_record(raw, "ImageGen completion transcript")
    payload = record.get("payload")
    if (
        record.get("type") != "event_msg"
        or not isinstance(payload, dict)
        or payload.get("type") != "image_generation_end"
        or payload.get("call_id") != generation_id
        or payload.get("status") != "completed"
        or payload.get("saved_path") != str(generator_source)
    ):
        raise PortraitBuildError(
            "Codex transcript completion 未精确绑定已完成的 ImageGen 输出"
        )
    encoded = payload.get("result")
    if not isinstance(encoded, str) or not encoded:
        raise PortraitBuildError(
            "Codex transcript completion 缺少原始 ImageGen result bytes"
        )
    try:
        event_bytes = base64.b64decode(encoded, validate=True)
    except (ValueError, binascii.Error) as exc:
        raise PortraitBuildError(
            f"Codex transcript ImageGen result base64 非法：{exc}"
        ) from exc
    if event_bytes != generator_bytes:
        raise PortraitBuildError(
            "Codex transcript ImageGen result 与 canonical cache "
            "不是逐字节同一输出"
        )
    return {
        "eventRecordSha256": sha256_bytes(raw),
        "eventOutputSha256": sha256_bytes(event_bytes),
        "eventOutputByteLength": len(event_bytes),
    }


def _strict_json_object_text(
    value: str,
    label: str,
) -> dict[str, Any]:
    if not isinstance(value, str) or not value:
        raise PortraitBuildError(f"{label}必须是非空 JSON object 字符串")
    if len(value.encode("utf-8")) > 1024 * 1024:
        raise PortraitBuildError(f"{label}超过 1 MiB")

    def reject_constant(token: str) -> None:
        raise PortraitBuildError(f"{label}包含非法常量：{token}")

    def unique_object(
        pairs: list[tuple[str, Any]],
    ) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, item in pairs:
            if key in result:
                raise PortraitBuildError(
                    f"{label}包含重复字段：{key}"
                )
            result[key] = item
        return result

    try:
        parsed = json.loads(
            value,
            object_pairs_hook=unique_object,
            parse_constant=reject_constant,
        )
    except PortraitBuildError:
        raise
    except (UnicodeError, json.JSONDecodeError) as exc:
        raise PortraitBuildError(
            f"{label}不是严格 JSON：{exc}"
        ) from exc
    if not isinstance(parsed, dict):
        raise PortraitBuildError(f"{label}顶层必须是 JSON object")
    return parsed


def _prompt_text_without_terminal_newlines(value: str) -> str:
    return value.rstrip("\r\n")


def _request_prompt_binding(
    *,
    request_prompt: str,
    repo_root: Path,
    prompt_path: Path,
    selected_entry: dict[str, Any],
) -> dict[str, Any]:
    if not request_prompt.strip() or "\x00" in request_prompt:
        raise PortraitBuildError(
            "ImageGen request prompt 必须是非空、无 NUL 的字符串"
        )
    try:
        request_prompt_bytes = request_prompt.encode("utf-8")
        selected_prompt_text = prompt_path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise PortraitBuildError(
            f"ImageGen request prompt 无法按 UTF-8 绑定：{exc}"
        ) from exc
    normalized_request = _prompt_text_without_terminal_newlines(
        request_prompt
    )
    normalized_selected = _prompt_text_without_terminal_newlines(
        selected_prompt_text
    )
    explicit_path_value = selected_entry.get("actualRequestPrompt")
    if normalized_selected == normalized_request:
        if explicit_path_value is not None:
            raise PortraitBuildError(
                "selected prompt 已与真实 request prompt 一致，"
                "不得再声明多余 actualRequestPrompt"
            )
        source_path = prompt_path
        relation = "selected_prompt_exact_ignoring_terminal_newlines_v1"
    else:
        if not isinstance(explicit_path_value, str) or not explicit_path_value:
            raise PortraitBuildError(
                "selected prompt 与真实 ImageGen request prompt 不一致；"
                "多轮提示词必须在 selected-sources entry 中声明独立 "
                "actualRequestPrompt 文件"
            )
        source_path = _resolve_inside(
            repo_root,
            Path(explicit_path_value),
            "actual ImageGen request prompt",
        )
        try:
            source_path.relative_to((repo_root / ".run").resolve())
        except ValueError as exc:
            raise PortraitBuildError(
                "actualRequestPrompt 必须位于仓库 .run/ 隔离区"
            ) from exc
        if source_path.suffix.casefold() != ".txt":
            raise PortraitBuildError(
                "actualRequestPrompt 必须是独立 UTF-8 .txt 文件"
            )
        if source_path == prompt_path:
            raise PortraitBuildError(
                "多轮 actualRequestPrompt 必须是独立文件"
            )
        try:
            explicit_text = source_path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            raise PortraitBuildError(
                f"actualRequestPrompt 不可读取：{source_path}: {exc}"
            ) from exc
        if (
            _prompt_text_without_terminal_newlines(explicit_text)
            != normalized_request
        ):
            raise PortraitBuildError(
                "actualRequestPrompt 未逐字绑定真实 ImageGen request "
                "prompt（仅允许末尾换行差异）"
            )
        relation = "explicit_actual_request_prompt_file_v1"
    if not _prompt_declares_dedicated_no_crop(request_prompt):
        raise PortraitBuildError(
            "真实 ImageGen request prompt 必须声明 dedicated portrait，"
            "并明确禁止从全身或生产素材裁切"
        )
    return {
        "contract": "imagegen_request_prompt_binding_v1",
        "requestPromptUtf8Sha256": sha256_bytes(request_prompt_bytes),
        "requestPromptUtf8ByteLength": len(request_prompt_bytes),
        "requestPromptHeuristicPassed": True,
        "selectedPromptPath": repo_relative(prompt_path, repo_root),
        "selectedPromptFileSha256": sha256_file(prompt_path),
        "selectedPromptRelation": relation,
        "requestPromptSourcePath": repo_relative(source_path, repo_root),
        "requestPromptSourceFileSha256": sha256_file(source_path),
    }


