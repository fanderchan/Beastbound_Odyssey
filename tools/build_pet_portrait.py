def build_portrait(options: PortraitBuildOptions) -> dict[str, Any]:
    """Pin repository/pet roots before validating any build evidence."""

    supplied_repo_root = options.repo_root.absolute()
    pinned_repo_root = options.repo_root.resolve()
    if not pinned_repo_root.is_dir():
        raise PortraitBuildError(
            f"仓库目录不存在：{pinned_repo_root}"
        )
    repo_root_fd = _open_absolute_directory(pinned_repo_root)
    try:
        pinned_pet_root = _resolve_inside(
            supplied_repo_root,
            options.pet_root,
            "宠物资源根目录",
        )
        pet_relative = pinned_pet_root.relative_to(pinned_repo_root)
        pet_root_fd = _open_directory_chain_from_fd(
            repo_root_fd,
            pet_relative,
            create=False,
            display_root=pinned_repo_root,
        )
        staging_parent_fd = _open_directory_chain_from_fd(
            repo_root_fd,
            pet_relative.parent,
            create=False,
            display_root=pinned_repo_root,
        )
        try:
            normalized = validate_options(options)
            if (
                normalized.repo_root != pinned_repo_root
                or normalized.pet_root != pinned_pet_root
            ):
                raise PortraitBuildError(
                    "portrait build 根目录与入口 pinned root 不一致"
                )
            _assert_absolute_directory_binding(
                pinned_repo_root,
                repo_root_fd,
                label="portrait build repo root",
            )
            _assert_absolute_directory_binding(
                pinned_pet_root,
                pet_root_fd,
                label="portrait build pet root",
            )
            return _build_portrait_with_root_fd(
                normalized,
                pet_root_fd,
                staging_parent_fd,
                repo_root_fd,
            )
        finally:
            os.close(staging_parent_fd)
            os.close(pet_root_fd)
    finally:
        os.close(repo_root_fd)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path.cwd())
    parser.add_argument("--pet-root", type=Path, required=True)
    parser.add_argument("--form-id", required=True)
    parser.add_argument("--input", dest="input_path", type=Path, required=True)
    parser.add_argument(
        "--identity-reference",
        type=Path,
        required=True,
        help="仓库内已经锁定的身份参考图",
    )
    parser.add_argument("--prompt-file", type=Path, required=True)
    attestation_mode = parser.add_mutually_exclusive_group(required=True)
    attestation_mode.add_argument(
        "--generation-attestation",
        type=Path,
        help="绑定 imagegen 结果、prompt 与 identity reference 的 JSON",
    )
    attestation_mode.add_argument(
        "--create-generation-attestation",
        type=Path,
        metavar="OUTPUT_JSON",
        help=(
            "只生成严格绑定的 attestation JSON；原子写入且永久拒绝覆盖"
        ),
    )
    attestation_mode.add_argument(
        "--create-identity-freeze-ledger",
        action="store_true",
        help=(
            "仅为显式 allowlist legacy form 写入当前身份像素兼容冻结账本"
        ),
    )
    parser.add_argument(
        "--generation-result",
        type=Path,
        help="首次 import 时已存在的 ImageGen selected result.txt",
    )
    parser.add_argument("--generation-id", required=True)
    parser.add_argument(
        "--catalog",
        type=Path,
        default=DEFAULT_CATALOG_PATH,
        help="正式宠物 formId 到实际 asset folder 的显式映射",
    )
    parser.add_argument(
        "--isolated",
        action="store_true",
        help="仅用于尚未登记 catalog 的显式隔离融合 root",
    )
    parser.add_argument("--key", type=parse_hex_color, default=DEFAULT_KEY)
    parser.add_argument(
        "--transparent-distance",
        type=float,
        default=DEFAULT_TRANSPARENT_DISTANCE,
    )
    parser.add_argument(
        "--opaque-distance",
        type=float,
        default=DEFAULT_OPAQUE_DISTANCE,
    )
    parser.add_argument(
        "--alpha-threshold",
        type=int,
        default=DEFAULT_ALPHA_THRESHOLD,
    )
    parser.add_argument(
        "--edge-contract",
        type=int,
        default=EDGE_CONTRACT_VERSION,
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="验证后原子安装；省略时仅 dry-run",
    )
    return parser


def main(argv: Iterable[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    try:
        if args.create_identity_freeze_ledger:
            if args.write or args.isolated:
                raise PortraitBuildError(
                    "identity freeze ledger writer 不接受 --write/--isolated"
                )
            ledger = write_identity_freeze_ledger(
                IdentityFreezeLedgerOptions(
                    repo_root=args.repo_root,
                    pet_root=args.pet_root,
                    form_id=args.form_id,
                    identity_reference=args.identity_reference,
                    catalog_path=args.catalog,
                )
            )
            print(
                json.dumps(
                    {
                        "status": "ok",
                        "mode": "identity_freeze_ledger_write",
                        "formId": args.form_id,
                        "ledger": (
                            Path(args.pet_root)
                            / IDENTITY_FREEZE_LEDGER_PATH
                        ).as_posix(),
                        "referenceSha256": ledger["reference"][
                            "fileSha256"
                        ],
                    },
                    ensure_ascii=False,
                    indent=2,
                )
            )
            return 0
        if args.create_generation_attestation is not None:
            if args.write:
                raise PortraitBuildError(
                    "attestation writer 模式不得同时传 --write"
                )
            if args.generation_result is None:
                raise PortraitBuildError(
                    "attestation writer 模式必须传 --generation-result"
                )
            attestation = write_generation_attestation(
                GenerationAttestationOptions(
                    repo_root=args.repo_root,
                    pet_root=args.pet_root,
                    form_id=args.form_id,
                    input_path=args.input_path,
                    identity_reference=args.identity_reference,
                    prompt_path=args.prompt_file,
                    generation_result=args.generation_result,
                    output_path=args.create_generation_attestation,
                    generation_id=args.generation_id,
                    catalog_path=args.catalog,
                    isolated=args.isolated,
                    key=args.key,
                )
            )
            print(
                json.dumps(
                    {
                        "status": "ok",
                        "mode": "generation_attestation_write",
                        "formId": args.form_id,
                        "generationId": attestation["generationId"],
                        "attestation": repo_relative(
                            _resolve_inside(
                                args.repo_root,
                                args.create_generation_attestation,
                                "generation attestation 输出",
                            ),
                            args.repo_root,
                        ),
                    },
                    ensure_ascii=False,
                    indent=2,
                )
            )
            return 0
        metadata = build_portrait(
            PortraitBuildOptions(
                repo_root=args.repo_root,
                pet_root=args.pet_root,
                form_id=args.form_id,
                input_path=args.input_path,
                identity_reference=args.identity_reference,
                prompt_path=args.prompt_file,
                generation_attestation=args.generation_attestation,
                generation_id=args.generation_id,
                catalog_path=args.catalog,
                isolated=args.isolated,
                key=args.key,
                transparent_distance=args.transparent_distance,
                opaque_distance=args.opaque_distance,
                alpha_threshold=args.alpha_threshold,
                edge_contract=args.edge_contract,
                write=args.write,
            )
        )
    except PortraitBuildError as exc:
        parser.exit(2, f"portrait build failed: {exc}\n")
    print(
        json.dumps(
            {
                "status": "ok",
                "mode": "write" if args.write else "dry-run",
                "formId": metadata["formId"],
                "runtime": metadata["assets"]["runtime"],
                "ownerReviewStatus": metadata["ownerReview"]["status"],
                "edgeChangedPixels": metadata["processing"]["alphaMatte"][
                    "despill"
                ]["changedPixelCount"],
            },
            ensure_ascii=False,
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
